#!/usr/bin/env python3
"""Emit the sea localization + a staged sea-region file from the canon-named index.

Board #2698. Reads the committed, canon-named ``tools/derived/sea_zones_index.json``
(the single source of truth for every zone's ``key`` / ``display_name`` / ``id``)
and writes:

* **committed** ``localization/english/map/wh_seas_l_english.yml`` — UTF-8 BOM,
  ``l_english:`` header, one ``KEY:0 "Display Name"`` line per zone. Zones in the
  same canon sea group share their display text. These are canon names, so there
  is **no** ``AUTOGEN_MARKER`` (that marks placeholder names pending naming — the
  opposite of this pass). This is the only game-loaded file this item ships.

* **staged, under ``tools/derived/``** (reviewable, NOT written into ``map_data/``):
  ``seas_99_seas.txt`` and ``seas_sea_starts.txt``. The bootable-map milestone
  (a later item) turns these into the real ``state_regions/99_seas.txt`` +
  ``default.map`` ``sea_starts`` once ``provinces.png`` exists; committed here so
  that milestone consumes them verbatim. Every zone is passable — **no
  ``impassable`` block** (2026-08-22 decision: 1800s steamships cross open ocean).

A deterministic unique ``xRRGGBB`` province colour is allocated per zone via
``raster.ColorAllocator(map_config.SEED)`` in ascending label order, so a re-run
reproduces byte-identical output. The generator asserts every colour in
``seas_99_seas.txt`` also appears in ``seas_sea_starts.txt`` — the milestone
invariant — and fails loudly otherwise.

Run ``generate_sea_zones.py`` first (it writes the canon-named index this reads).

Usage::

    python tools/generate_sea_regions.py
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from config import map_config  # noqa: E402
from worldgen import raster  # noqa: E402

TOOLS_DIR = Path(__file__).resolve().parent
MOD_ROOT = TOOLS_DIR.parent
DERIVED_DIR = TOOLS_DIR / "derived"
INDEX_PATH = DERIVED_DIR / "sea_zones_index.json"
LOC_DIR = MOD_ROOT / "localization" / "english" / "map"
LOC_PATH = LOC_DIR / "wh_seas_l_english.yml"
STAGED_99_SEAS = DERIVED_DIR / "seas_99_seas.txt"
STAGED_SEA_STARTS = DERIVED_DIR / "seas_sea_starts.txt"

BOM = b"\xef\xbb\xbf"
INDENT = "\t"

_STAGED_BANNER = (
    "# STAGED — board #2698. NOT loaded by the game and NOT in map_data/.\n"
    "# Generated by tools/generate_sea_regions.py from tools/derived/sea_zones_index.json.\n"
    "# The bootable-map milestone turns this into the real map_data file once\n"
    "# provinces.png exists; every zone is passable (no impassable blocks).\n"
    "# Regenerate — never hand-edit.\n"
)


def _write_bytes(path: Path, text: str, bom: bool = False) -> None:
    data = text.encode("utf-8")
    if bom:
        data = BOM + data
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)  # binary write keeps LF newlines regardless of platform


def _render_loc(cells: list[dict]) -> str:
    """The committed sea loc: one ``KEY:0 "Display"`` per zone, canon (no marker)."""
    lines = ["l_english:"]
    for c in sorted(cells, key=lambda c: c["key"]):
        lines.append(f' {c["key"]}:0 "{c["display_name"]}"')
    return "\n".join(lines) + "\n"


def _render_sea_state(key: str, state_id: int, color: raster.Color) -> str:
    """One passable single-province sea-zone block (no ``impassable``).

    Built directly from ``(key, id, colour)`` — these zones exist only as index
    rows, not as full ``schema.State`` objects, so ``statefile.render_sea_state``
    (which needs a whole ``State``) is deliberately not used here.
    """
    return (
        f"{key} = {{\n"
        f"{INDENT}id = {state_id}\n"
        f"{INDENT}provinces = {{ {raster.color_to_hex(color)} }}\n"
        "}"
    )


def _render_99_seas(cells: list[dict], colors: dict[int, raster.Color]) -> str:
    blocks = [_render_sea_state(c["key"], c["id"], colors[c["label"]])
              for c in sorted(cells, key=lambda c: c["label"])]
    return _STAGED_BANNER + "\n" + "\n".join(blocks) + "\n"


def _render_sea_starts(cells: list[dict], colors: dict[int, raster.Color]) -> str:
    toks = " ".join(raster.color_to_hex(colors[c["label"]])
                    for c in sorted(cells, key=lambda c: colors[c["label"]]))
    return _STAGED_BANNER + "\nsea_starts = {\n" + f"{INDENT}{toks}\n" + "}\n"


def main(argv: list[str] | None = None) -> int:
    argparse.ArgumentParser(description=__doc__,
                            formatter_class=argparse.RawDescriptionHelpFormatter).parse_args(argv)
    if not INDEX_PATH.is_file():
        raise SystemExit(f"{INDEX_PATH} not found — run tools/generate_sea_zones.py first")
    index = json.loads(INDEX_PATH.read_text(encoding="utf-8"))
    cells = index["cells"]
    if not cells:
        raise SystemExit(f"{INDEX_PATH} has no cells")

    # Deterministic unique province colour per zone, in ascending label order.
    alloc = raster.ColorAllocator(map_config.SEED)
    colors = {c["label"]: alloc.allocate() for c in sorted(cells, key=lambda c: c["label"])}

    _write_bytes(LOC_PATH, _render_loc(cells), bom=True)
    print(f"wrote {LOC_PATH.relative_to(MOD_ROOT)}  ({len(cells)} zones)")

    seas_txt = _render_99_seas(cells, colors)
    starts_txt = _render_sea_starts(cells, colors)

    # Milestone invariant: every province colour in 99_seas must appear in sea_starts.
    seas_colors = {raster.color_to_hex(colors[c["label"]]) for c in cells}
    starts_colors = set(starts_txt.split("sea_starts = {")[1].split("}")[0].split())
    missing = seas_colors - starts_colors
    if missing:
        raise SystemExit(f"invariant violated: {len(missing)} sea colours missing from "
                         f"sea_starts: {sorted(missing)[:5]}")

    _write_bytes(STAGED_99_SEAS, seas_txt)
    print(f"wrote {STAGED_99_SEAS.relative_to(MOD_ROOT)}  (staged, {len(cells)} zones)")
    _write_bytes(STAGED_SEA_STARTS, starts_txt)
    print(f"wrote {STAGED_SEA_STARTS.relative_to(MOD_ROOT)}  (staged, "
          f"{len(starts_colors)} colours)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
