#!/usr/bin/env python3
"""Read the painted starting-ownership map into ``mapgen/derived/state_ownership.json``.

``mapgen/config/state_ownership.png`` (hand-painted, flat exact-RGB fills; see
``state_ownership_legend.json`` for the colour of every tag) is the source of
truth for who owns each land state at the start date. This reads it back:

* every colour must be in the legend -- an unknown colour is a hard error that
  reports the colour, its pixel count and a sample coordinate;
* each land province votes for the owner colour with the pixel plurality,
  ignoring the state-border and water colours;
* a state whose provinces all vote alike has one ``owner``; a split state lists
  its ``owners`` with province ids;
* a province with no votable pixel, or an out-of-scope (placeholder) province
  painted with a tag, is a hard error.

The output is keyed by the current ``STATE_*`` keys read from
``map_data/state_regions/`` and carries each state's id, its naming anchor and
its scope (``drawn`` / ``placeholder``). Deterministic and byte-stable. A
generated file: never hand-edit it, repaint the PNG.

Usage::

    python mapgen/read_state_ownership.py           # write mapgen/derived/state_ownership.json
    python mapgen/read_state_ownership.py --check   # exit 1 if the committed output is stale
    python mapgen/read_state_ownership.py --review  # also the annotated half-size render (gitignored)
"""
from __future__ import annotations

import argparse
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from worldgen import raster, state_ownership as so  # noqa: E402

MOD_ROOT = Path(__file__).resolve().parent.parent
PNG_PATH = MOD_ROOT / "mapgen" / "config" / "state_ownership.png"
LEGEND_PATH = MOD_ROOT / "mapgen" / "config" / "state_ownership_legend.json"
OUT_PATH = MOD_ROOT / "mapgen" / "derived" / "state_ownership.json"
REVIEW_PATH = MOD_ROOT / "mapgen" / "derived" / "state_ownership_review.png"


def build(png: Path, legend_path: Path) -> str:
    legend = so.load_legend(legend_path)
    layout, placeholder, ids_anchor = so.load_inputs(MOD_ROOT)
    painted = raster.read_rgb_png(png)
    states = so.read(layout, painted, legend, placeholder, ids_anchor)
    return so.to_json({
        "_comment": "GENERATED by mapgen/read_state_ownership.py from mapgen/config/state_ownership.png "
                    "+ state_ownership_legend.json. Never hand-edit; repaint the PNG and re-read.",
        "canvas": [layout.width, layout.height],
        "states": states,
    })


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--png", type=Path, default=PNG_PATH)
    ap.add_argument("--legend", type=Path, default=LEGEND_PATH)
    ap.add_argument("--out", type=Path, default=OUT_PATH)
    ap.add_argument("--review", action="store_true", help="also write the annotated half-size review render")
    ap.add_argument("--numbers", action="store_true", help="review render: also print each state's numeric id under its tag code")
    ap.add_argument("--labels", choices=("country", "tag", "state"), default="country", help="review render label: first 12 chars of the owning country's name (default), the owner tag code, or the state's localized name")
    ap.add_argument("--scale", type=float, default=0.5, help="review render scale (default 0.5; 1.0 for legible numbers)")
    ap.add_argument("--review-out", type=Path, default=REVIEW_PATH)
    ap.add_argument("--check", action="store_true", help="assert the output on disk is current; write nothing")
    args = ap.parse_args(argv)
    t0 = time.time()
    try:
        text = build(args.png, args.legend)
        if args.review:
            legend = so.load_legend(args.legend)
            layout = so.load_inputs(MOD_ROOT)[0]
            painted = raster.read_rgb_png(args.png)
            so.review_render(painted, layout, so.vote(layout, painted, legend), legend, scale=args.scale, numbers=args.numbers,
                labels=args.labels,
                state_names=so.load_state_names(MOD_ROOT) if args.labels == "state" else None).save(args.review_out)
            print(f"read_state_ownership: wrote {args.review_out}")
    except so.OwnershipError as exc:
        print(f"read_state_ownership: ERROR: {exc}", file=sys.stderr)
        return 1
    if args.check:
        # CRLF-insensitive: core.autocrlf checks the committed LF file out as CRLF.
        current = args.out.read_bytes().decode("utf-8").replace("\r\n", "\n") if args.out.is_file() else None
        if current != text:
            print(f"read_state_ownership: {args.out} is stale -- re-run without --check", file=sys.stderr)
            return 1
        print("read_state_ownership: output is current.")
        return 0
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_bytes(text.encode("utf-8"))
    print(f"read_state_ownership: wrote {args.out} ({time.time() - t0:.1f}s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
