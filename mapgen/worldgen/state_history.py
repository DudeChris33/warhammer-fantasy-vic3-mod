@dataclass
class Plan:
    files: dict[str, Entries]
    held_back: list[tuple[str, str]] = field(default_factory=list)   # (state key, tag)
    unowned: list[str] = field(default_factory=list)
    placeholder: list[str] = field(default_factory=list)
    homelands: dict[str, list[str]] = field(default_factory=dict)   # state key -> culture ids

    @property
    def create_states(self) -> int:
        return sum(len(c) for e in self.files.values() for _, c in e)


def _slices(key: str, rec: dict, state: State) -> list[tuple[str, list[str]]]:
    """``[(owner token, sorted provinces)]`` for a drawn state's JSON record."""
    if "owner" in rec:
        return [(rec["owner"], sorted(state.provinces))]
    if "owners" not in rec:
        raise OwnershipError(f"{key}: record has neither 'owner' nor 'owners'")
    own = set(state.provinces)
    seen: dict[str, str] = {}
    out: list[tuple[str, list[str]]] = []
    for sl in rec["owners"]:
        provs = [_norm(t) for t in sl["provinces"]]
        for t in provs:
            if t not in own:
                raise OwnershipError(f"{key}: split province {t} ({sl['owner']}) is not a province of the state")
            if t in seen:
                raise OwnershipError(f"{key}: split province {t} is listed under both {seen[t]} and {sl['owner']}")
            seen[t] = sl["owner"]
        out.append((sl["owner"], sorted(provs)))
    missing = sorted(own - set(seen))
    if missing:
        raise OwnershipError(f"{key}: split leaves {len(missing)} province(s) without an owner (first: {missing[:3]})")
    return out


def _check_doc(doc: dict, states_by_file: dict[str, list[State]]) -> dict[str, dict]:
    states = doc.get("states")
    if not isinstance(states, dict):
        raise OwnershipError("state_ownership.json has no 'states' object")
    land = {s.key: s for ss in states_by_file.values() for s in ss}
    unknown = sorted(set(states) - set(land))
    if unknown:
        raise OwnershipError(f"state_ownership.json names {len(unknown)} state(s) not in map_data "
                             f"(first: {unknown[:5]}) -- re-run read_state_ownership.py")
    missing = sorted(set(land) - set(states))
    if missing:
        raise OwnershipError(f"{len(missing)} map_data land state(s) missing from state_ownership.json "
                             f"(first: {missing[:5]}) -- re-run read_state_ownership.py")
    for key, rec in states.items():
        if rec.get("id") != land[key].id:
            raise OwnershipError(f"{key}: state_ownership.json id {rec.get('id')} != map_data id {land[key].id}"
                                 " -- re-run read_state_ownership.py")
        if rec.get("scope") == "placeholder" and rec.get("owner") != PLACEHOLDER:
            raise OwnershipError(f"{key}: placeholder-scope state must have owner 'placeholder'")
    return states


def derive_homelands(owner_tags, country_cultures: dict[str, list[str]]) -> list[str]:
    """Ordered, de-duplicated cultures of ``owner_tags`` (taken in sorted order);
    ``UNO`` contributes none."""
    out: list[str] = []
    for tag in sorted(set(owner_tags)):
        if tag == UNO_TAG:
            continue
        for c in country_cultures.get(tag, []):
            if c not in out:
                out.append(c)
    return out


def owner_slices(key: str, rec: dict, state: State,
                 defined_tags: set[str]) -> tuple[list[tuple[str, list[str]]], list[str]]:
    """``([(tag, sorted provinces)], [held-back tag])`` that one state's JSON record
    implies -- the single source of the expected ``create_state`` blocks for both
    :func:`plan` and :func:`check`. Owner tokens map through :data:`TOKEN_OWNER`
    (a placeholder-scope state is wholly ``UNO``), slices of the same tag merge, and
    a tag with no definition is held back. Raises :class:`OwnershipError` for a
    malformed split or a drawn state owned by ``placeholder``."""
    if rec.get("scope") == "placeholder":
        slices = [(PLACEHOLDER, sorted(state.provinces))]
    else:
        slices = _slices(key, rec, state)
        if any(owner == PLACEHOLDER for owner, _ in slices):
            raise OwnershipError(f"{key}: drawn state owned by 'placeholder'")
    merged: dict[str, list[str]] = {}
    for owner, provs in slices:
        merged.setdefault(TOKEN_OWNER.get(owner, owner), []).extend(provs)
    creates = [(tag, sorted(provs)) for tag, provs in sorted(merged.items()) if tag in defined_tags]
    held = [tag for tag in sorted(merged) if tag not in defined_tags]
    return creates, held


def plan(ownership_doc: dict, states_by_file: dict[str, list[State]], defined_tags: set[str],
         homelands: "Homelands | None" = None) -> Plan:
    """What to emit, per history file. Raises :class:`OwnershipError` when the
    JSON does not match ``map_data`` (stale read), a split is malformed, or ``homelands``
    gives a non-empty list to a state that gets no ``create_state``.
    With ``homelands`` (:func:`load_homelands`), ``Plan.homelands`` carries each emitted
    state's non-empty configured list. ``Plan.unowned`` / ``Plan.placeholder`` list the
    whole states that went to ``UNO`` through each token."""
    states = _check_doc(ownership_doc, states_by_file)
    out = Plan(files={})
    for fname in sorted(states_by_file):
        entries: Entries = []
        for st in sorted(states_by_file[fname], key=lambda s: s.key):
            rec = states[st.key]
            if rec.get("scope") == "placeholder":
                out.placeholder.append(st.key)
            elif rec.get("owner") == UNOWNED:
                out.unowned.append(st.key)
            creates, held = owner_slices(st.key, rec, st, defined_tags)
            out.held_back += [(st.key, tag) for tag in held]
            row = homelands.get(st.key) if homelands is not None else None
            if creates:
                entries.append((st.key, creates))
                if row is not None and row[1]:
                    out.homelands[st.key] = list(row[1])
            elif row is not None and row[1]:
                raise OwnershipError(f"{st.key}: state_homelands.json gives homelands {row[1]} to a state "
                                     "that gets no create_state (owner tag held back)")
        out.files[fname] = entries
    return out


