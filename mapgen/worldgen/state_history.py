"""Starting state ownership as game script: ``common/history/states/NN_*.txt``.

``mapgen/derived/state_ownership.json`` (read off the painted
``state_ownership.png`` by ``read_state_ownership.py``) says who owns each land
state at the start date. This module turns it into the vanilla history shape::

    STATES = {
    	s:STATE_X = {
    		create_state = {
    			country = c:TAG
    			owned_provinces = { xRRGGBB ... }
    		}
    	}
    }

(vanilla ``game/common/history/states/00_states.txt``: tab indent, ``s:``/``c:``
scopes, one ``create_state`` per owner of a split state, partial ownership
legal). ``generate_state_history.py`` is the CLI; ``validate_map.py`` re-reads the
emitted files through :func:`check`.

Rules
-----
* One history file per land ``map_data/state_regions/NN_<stem>.txt``, same file
  name (``99_seas.txt`` is skipped). Every one is rewritten, so all are
  generator-owned; a file with no state in it carries the header comment only.
* The ``unowned`` and ``placeholder`` owner tokens are not tags: :data:`TOKEN_OWNER`
  maps both to ``UNO`` (Unclaimed Lands, the decentralized placeholder owner,
  #6391). An out-of-scope (``placeholder``-scope) state emits one ``c:UNO``
  ``create_state`` with every province; an ``unowned`` drawn state or slice becomes
  a ``c:UNO`` slice. A drawn state painted ``placeholder`` is an error.
* A whole-state owner gets every province of the state (vanilla includes
  impassable provinces in ``owned_provinces``).
* A split (``owners: [{owner, provinces}]``) emits one ``create_state`` per
  defined-tag slice (slices that map to the same tag are merged).
* An owner tag with no non-dynamic ``common/country_definitions`` entry is
  **held back**: its state (or slice) emits nothing and is reported, so the
  generator never writes a dangling ``c:TAG`` -- ``UNO`` included. ``validate_map``
  decides whether a hold-back fails the gate (``HELD_BACK_IS_ERROR``).
* Generator and validator take the expected owners from one helper,
  :func:`owner_slices`, so a missing or wrong ``c:UNO`` block fails ``check()`` the
  same way any other owner mismatch does.
* Homelands (#8604): ``add_homeland = cu:<c>`` lines come only from the hand-authored
  ``mapgen/config/state_homelands.json`` (one row per land state, keyed ``STATE_<NAME>`` plus
  its ``naming_anchor``, value = ordered culture ids, ``[]`` = no homelands, any state). Owner
  ``cultures`` no longer feed it; :func:`derive_homelands` survives only as the seeder behind
  :func:`sync_homelands` (``--seed-homelands`` / ``--sync-homelands``), which adds new states from
  their owners, carries a rename with a unique anchor match over with its edits, and never deletes
  or edits an existing row. :func:`check_homelands` (config vs map_data/ownership/cultures) is the
  one source of the config errors for generator and validator. A state with no create_state
  carries none.
* Ordering is stable: states by key, ``create_state`` blocks by tag, provinces
  by hex token -- a land-regions regen that reorders blocks does not churn this.

Pure and deterministic: no clock, no filesystem beyond the paths handed in.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from pathlib import Path

from .state_ownership import PLACEHOLDER, UNOWNED, OwnershipError, State, parse_state_text

HEADER = ("# GENERATED by mapgen/generate_state_history.py from mapgen/derived/state_ownership.json"
          " - never hand-edit; repaint mapgen/config/state_ownership.png, re-read it"
          " (read_state_ownership.py) and regenerate.\n")

_TAG_HEADER = re.compile(r"^([A-Z][A-Z0-9]{2})\s*=\s*\{", re.M)
_DYNAMIC = re.compile(r"\bdynamic_country_definition\s*=\s*yes\b")
_HISTORY_STATE = re.compile(r"\bs:(STATE_\w+)\s*=\s*\{")
_CREATE = re.compile(r"\bcreate_state\s*=\s*\{")
_COUNTRY = re.compile(r"\bcountry\s*=\s*c:(\w+)")
_OWNED = re.compile(r"\bowned_provinces\s*=\s*\{([^}]*)\}")
_HEX = re.compile(r"x[0-9A-Fa-f]{6}")
_CULTURES = re.compile(r"\bcultures\s*=\s*\{([^}]*)\}")
_HOMELAND = re.compile(r"\badd_homeland\s*=\s*cu:(\w+)")
_TOP_KEY = re.compile(r"^(\w+)\s*=\s*\{", re.M)

#: The decentralized placeholder tag that owns unowned / out-of-scope land (#6391). It
#: carries a stand-in culture but its states get no homelands.
UNO_TAG = "UNO"

#: ``state_ownership.json`` owner tokens that are not tags -> the tag that owns that land.
TOKEN_OWNER: dict[str, str] = {UNOWNED: UNO_TAG, PLACEHOLDER: UNO_TAG}

#: ``[(state_key, [(tag, [province, ...]), ...]), ...]`` -- one history file.
Entries = list[tuple[str, list[tuple[str, list[str]]]]]


def _norm(token: str) -> str:
    return "x" + token[1:].upper()


def _match_brace(text: str, open_idx: int) -> int:
    depth = 0
    for i in range(open_idx, len(text)):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return i
    raise OwnershipError("unbalanced braces in a history file")


def _strip_comments(text: str) -> str:
    return re.sub(r"#[^\n]*", "", text)


