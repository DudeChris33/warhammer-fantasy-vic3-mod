"""Starting state ownership as game script: ``common/history/states/NN_*.txt``.

``mapgen/derived/state_ownership.json`` (read off the painted
``state_ownership.png`` by ``read_state_ownership.py``) says who owns each land
state at the start date. This module turns it into the vanilla history shape::

    STATES = {
    	s:STATE_X = {
    		create_state = {
    			country = c:TAG
    			owned_provinces = { xRRGGBB ... }
    		}
    	}
    }

(vanilla ``game/common/history/states/00_states.txt``: tab indent, ``s:``/``c:``
scopes, one ``create_state`` per owner of a split state, partial ownership
legal). ``generate_state_history.py`` is the CLI; ``validate_map.py`` re-reads the
emitted files through :func:`check`.

Rules
-----
* One history file per land ``map_data/state_regions/NN_<stem>.txt``, same file
  name (``99_seas.txt`` is skipped). Every one is rewritten, so all are
  generator-owned; a file with no owned state carries the header comment only.
* ``placeholder`` (out-of-scope) and ``unowned`` states emit nothing.
* A whole-state owner gets every province of the state (vanilla includes
  impassable provinces in ``owned_provinces``).
* A split (``owners: [{owner, provinces}]``) emits one ``create_state`` per
  defined-tag slice; ``unowned`` slices emit nothing (partial ownership).
* An owner tag with no non-dynamic ``common/country_definitions`` entry is
  **held back**: its state (or slice) emits nothing and is reported, so the
  generator never writes a dangling ``c:TAG``. ``validate_map`` decides whether a
  hold-back fails the gate (``HELD_BACK_IS_ERROR``).
* Ordering is stable: states by key, ``create_state`` blocks by tag, provinces
  by hex token -- a land-regions regen that reorders blocks does not churn this.

Pure and deterministic: no clock, no filesystem beyond the paths handed in.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path

from .state_ownership import PLACEHOLDER, UNOWNED, OwnershipError, State, parse_state_text

HEADER = ("# GENERATED by mapgen/generate_state_history.py from mapgen/derived/state_ownership.json"
          " - never hand-edit; repaint mapgen/config/state_ownership.png, re-read it"
          " (read_state_ownership.py) and regenerate.\n")

_TAG_HEADER = re.compile(r"^([A-Z][A-Z0-9]{2})\s*=\s*\{", re.M)
_DYNAMIC = re.compile(r"\bdynamic_country_definition\s*=\s*yes\b")
_HISTORY_STATE = re.compile(r"\bs:(STATE_\w+)\s*=\s*\{")
_CREATE = re.compile(r"\bcreate_state\s*=\s*\{")
_COUNTRY = re.compile(r"\bcountry\s*=\s*c:(\w+)")
_OWNED = re.compile(r"\bowned_provinces\s*=\s*\{([^}]*)\}")
_HEX = re.compile(r"x[0-9A-Fa-f]{6}")

#: ``[(state_key, [(tag, [province, ...]), ...]), ...]`` -- one history file.
Entries = list[tuple[str, list[tuple[str, list[str]]]]]


def _norm(token: str) -> str:
    return "x" + token[1:].upper()


def _match_brace(text: str, open_idx: int) -> int:
    depth = 0
    for i in range(open_idx, len(text)):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return i
    raise OwnershipError("unbalanced braces in a history file")


def _strip_comments(text: str) -> str:
    return re.sub(r"#[^\n]*", "", text)


# ---------------------------------------------------------------------------
# Inputs
# ---------------------------------------------------------------------------

def load_states_by_file(state_regions_dir: Path) -> dict[str, list[State]]:
    """``{file name: [State, ...]}`` for every land ``NN_*.txt`` (``99_`` skipped)."""
    out: dict[str, list[State]] = {}
    for path in sorted(Path(state_regions_dir).glob("*.txt")):
        if path.name.startswith("99_"):
            continue
        out[path.name] = parse_state_text(path.read_text(encoding="utf-8-sig"))
    return out


def parse_country_tags(text: str) -> set[str]:
    """Tags defined by one ``country_definitions`` file, excluding the runtime
    ``dynamic_country_definition = yes`` slots (D00-D99), which are not
    start-date countries."""
    text = _strip_comments(text.lstrip("﻿"))
    tags: set[str] = set()
    for m in _TAG_HEADER.finditer(text):
        open_idx = text.index("{", m.end() - 1)
        body = text[open_idx + 1:_match_brace(text, open_idx)]
        if not _DYNAMIC.search(body):
            tags.add(m.group(1))
    return tags


def load_country_tags(country_definitions_dir: Path) -> set[str]:
    tags: set[str] = set()
    for path in sorted(Path(country_definitions_dir).glob("*.txt")):
        tags |= parse_country_tags(path.read_text(encoding="utf-8-sig"))
    return tags


# ---------------------------------------------------------------------------
# Plan
# ---------------------------------------------------------------------------

@dataclass
class Plan:
    files: dict[str, Entries]
    held_back: list[tuple[str, str]] = field(default_factory=list)   # (state key, tag)
    unowned: list[str] = field(default_factory=list)
    placeholder: list[str] = field(default_factory=list)

    @property
    def create_states(self) -> int:
        return sum(len(c) for e in self.files.values() for _, c in e)


def _slices(key: str, rec: dict, state: State) -> list[tuple[str, list[str]]]:
    """``[(owner token, sorted provinces)]`` for a drawn state's JSON record."""
    if "owner" in rec:
        return [(rec["owner"], sorted(state.provinces))]
    if "owners" not in rec:
        raise OwnershipError(f"{key}: record has neither 'owner' nor 'owners'")
    own = set(state.provinces)
    seen: dict[str, str] = {}
    out: list[tuple[str, list[str]]] = []
    for sl in rec["owners"]:
        provs = [_norm(t) for t in sl["provinces"]]
        for t in provs:
            if t not in own:
                raise OwnershipError(f"{key}: split province {t} ({sl['owner']}) is not a province of the state")
            if t in seen:
                raise OwnershipError(f"{key}: split province {t} is listed under both {seen[t]} and {sl['owner']}")
            seen[t] = sl["owner"]
        out.append((sl["owner"], sorted(provs)))
    missing = sorted(own - set(seen))
    if missing:
        raise OwnershipError(f"{key}: split leaves {len(missing)} province(s) without an owner (first: {missing[:3]})")
    return out


def _check_doc(doc: dict, states_by_file: dict[str, list[State]]) -> dict[str, dict]:
    states = doc.get("states")
    if not isinstance(states, dict):
        raise OwnershipError("state_ownership.json has no 'states' object")
    land = {s.key: s for ss in states_by_file.values() for s in ss}
    unknown = sorted(set(states) - set(land))
    if unknown:
        raise OwnershipError(f"state_ownership.json names {len(unknown)} state(s) not in map_data "
                             f"(first: {unknown[:5]}) -- re-run read_state_ownership.py")
    missing = sorted(set(land) - set(states))
    if missing:
        raise OwnershipError(f"{len(missing)} map_data land state(s) missing from state_ownership.json "
                             f"(first: {missing[:5]}) -- re-run read_state_ownership.py")
    for key, rec in states.items():
        if rec.get("id") != land[key].id:
            raise OwnershipError(f"{key}: state_ownership.json id {rec.get('id')} != map_data id {land[key].id}"
                                 " -- re-run read_state_ownership.py")
        if rec.get("scope") == "placeholder" and rec.get("owner") != PLACEHOLDER:
            raise OwnershipError(f"{key}: placeholder-scope state must have owner 'placeholder'")
    return states


def plan(ownership_doc: dict, states_by_file: dict[str, list[State]], defined_tags: set[str]) -> Plan:
    """What to emit, per history file. Raises :class:`OwnershipError` when the
    JSON does not match ``map_data`` (stale read) or a split is malformed."""
    states = _check_doc(ownership_doc, states_by_file)
    out = Plan(files={})
    for fname in sorted(states_by_file):
        entries: Entries = []
        for st in sorted(states_by_file[fname], key=lambda s: s.key):
            rec = states[st.key]
            if rec.get("scope") == "placeholder":
                out.placeholder.append(st.key)
                continue
            creates: list[tuple[str, list[str]]] = []
            for owner, provs in _slices(st.key, rec, st):
                if owner == PLACEHOLDER:
                    raise OwnershipError(f"{st.key}: drawn state owned by 'placeholder'")
                if owner == UNOWNED:
                    continue
                if owner not in defined_tags:
                    out.held_back.append((st.key, owner))
                    continue
                creates.append((owner, provs))
            if "owner" in rec and rec["owner"] == UNOWNED:
                out.unowned.append(st.key)
            if creates:
                entries.append((st.key, sorted(creates)))
        out.files[fname] = entries
    return out


