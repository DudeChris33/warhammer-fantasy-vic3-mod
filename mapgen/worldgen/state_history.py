def render_file(entries: Entries, homelands: dict[str, list[str]] | None = None) -> str:
    """One history file (no BOM, LF). Header comment only when ``entries`` is empty.
    ``homelands`` adds ``add_homeland`` lines after a state's ``create_state`` blocks
    (a blank line first, as in vanilla); output is unchanged when it is empty."""
    if not entries:
        return HEADER
    lines = [HEADER.rstrip("\n"), "STATES = {"]
    for key, creates in entries:
        lines.append(f"\ts:{key} = {{")
        for tag, provs in creates:
            lines += ["\t\tcreate_state = {",
                      f"\t\t\tcountry = c:{tag}",
                      f"\t\t\towned_provinces = {{ {' '.join(provs)} }}",
                      "\t\t}"]
        if homelands and homelands.get(key):
            lines.append("")
            lines += [f"\t\tadd_homeland = cu:{c}" for c in homelands[key]]
        lines.append("\t}")
    lines.append("}")
    return "\n".join(lines) + "\n"


def parse_history_text(text: str) -> list[tuple[str, list[tuple[str | None, list[str]]]]]:
    """``[(state key, [(tag | None, [provinces])])]`` in file order (duplicates kept,
    so the validator can see them). Comments are ignored."""
    text = _strip_comments(text.lstrip("﻿"))
    out = []
    idx = 0
    while True:
        m = _HISTORY_STATE.search(text, idx)
        if not m:
            break
        open_idx = text.index("{", m.end() - 1)
        close_idx = _match_brace(text, open_idx)
        body = text[open_idx + 1:close_idx]
        creates = []
        j = 0
        while True:
            cm = _CREATE.search(body, j)
            if not cm:
                break
            c_open = body.index("{", cm.end() - 1)
            c_close = _match_brace(body, c_open)
            cbody = body[c_open + 1:c_close]
            tm = _COUNTRY.search(cbody)
            pm = _OWNED.search(cbody)
            creates.append((tm.group(1) if tm else None,
                            [_norm(t) for t in _HEX.findall(pm.group(1))] if pm else []))
            j = c_close + 1
        out.append((m.group(1), creates))
        idx = close_idx + 1
    return out


def parse_homelands(text: str) -> dict[str, list[str]]:
    """``{state key: [culture id, ...]}`` of the ``add_homeland`` lines in one history
    file; states without any are absent. Comments are ignored."""
    text = _strip_comments(text.lstrip("﻿"))
    out: dict[str, list[str]] = {}
    idx = 0
    while True:
        m = _HISTORY_STATE.search(text, idx)
        if not m:
            return out
        open_idx = text.index("{", m.end() - 1)
        close_idx = _match_brace(text, open_idx)
        homes = _HOMELAND.findall(text[open_idx + 1:close_idx])
        if homes:
            out.setdefault(m.group(1), []).extend(homes)
        idx = close_idx + 1


def normalize_text(text: str) -> str:
    """For byte-compare freshness checks: drop a BOM and CRLF -> LF (git's
    ``core.autocrlf`` checks generated LF files out as CRLF)."""
    return text.lstrip("﻿").replace("\r\n", "\n")


# ---------------------------------------------------------------------------
# Validate emitted files
# ---------------------------------------------------------------------------

def check(history_texts: dict[str, str], ownership_doc: dict, states_by_file: dict[str, list[State]],
          defined_tags: set[str], homelands: Homelands | None = None,
          culture_ids: set[str] | None = None) -> tuple[list[str], list[tuple[str, str]]]:
    """Validate emitted history against ``map_data``, the JSON and the defined
    tags. Returns ``(errors, held_back)``; ``held_back`` lists JSON owners whose
    tag is undefined (the caller decides whether that is an error). The expected
    blocks come from :func:`owner_slices`, as in :func:`plan`, so an unowned or
    out-of-scope state without its ``c:UNO`` block (or with another owner) fails as
    an owner mismatch.

    ``culture_ids`` (the ``common/cultures`` ids) makes every emitted ``add_homeland``
    id without a culture definition an error. ``homelands`` (the config, #8604) runs
    :func:`check_homelands` and makes each land state's emitted list equal its config row
    (``[]`` included -- an owned state may have none), and refuses homelands on a state
    without a ``create_state``."""
    errors: list[str] = []
    try:
        states = _check_doc(ownership_doc, states_by_file)
    except OwnershipError as exc:
        return [str(exc)], []
    if homelands is not None:
        errors += check_homelands(homelands, ownership_doc, states_by_file, culture_ids)[0]
    land = {s.key: s for ss in states_by_file.values() for s in ss}
    file_of = {s.key: f for f, ss in states_by_file.items() for s in ss}

    emitted: dict[str, list[tuple[str | None, list[str]]]] = {}
    emitted_homes: dict[str, list[str]] = {}
    for fname in sorted(history_texts):
        if fname not in states_by_file:
            errors.append(f"history/states/{fname}: no map_data/state_regions/{fname} counterpart")
        try:
            parsed = parse_history_text(history_texts[fname])
        except OwnershipError as exc:
            errors.append(f"history/states/{fname}: {exc}")
            continue
        for key, creates in parsed:
            where = f"history/states/{fname} s:{key}"
            if key not in land:
                errors.append(f"{where}: not a land state in map_data")
                continue
            if file_of[key] != fname:
                errors.append(f"{where}: belongs in {file_of[key]} (its map_data file)")
            if key in emitted:
                errors.append(f"{where}: state appears more than once in history")
                continue
            emitted[key] = creates
        for key, homes in parse_homelands(history_texts[fname]).items():
            if key in land:
                emitted_homes.setdefault(key, homes)

    for fname in sorted(states_by_file):
        if fname not in history_texts:
            errors.append(f"history/states/{fname} is missing -- run generate_state_history.py")

    held_back: list[tuple[str, str]] = []
    claimed: dict[str, str] = {}
    for key in sorted(land):
        rec = states[key]
        creates = emitted.get(key, [])
        st = land[key]
        own = set(st.provinces)
        homes = emitted_homes.get(key, [])
        if culture_ids is not None:
            for c in homes:
                if c not in culture_ids:
                    errors.append(f"s:{key}: add_homeland = cu:{c} has no common/cultures definition")
        if homelands is not None and homes and not creates:
            errors.append(f"s:{key}: add_homeland on a state without a create_state")
        for tag, provs in creates:
            if tag is None:
                errors.append(f"s:{key}: create_state without 'country = c:TAG'")
                continue
            if tag not in defined_tags:
                errors.append(f"s:{key}: c:{tag} has no (non-dynamic) common/country_definitions entry")
            for t in provs:
                if t not in own:
                    errors.append(f"s:{key}: owned province {t} is not a province of the state")
                elif t in claimed:
                    errors.append(f"s:{key}: province {t} assigned twice ({claimed[t]} and c:{tag})")
                else:
                    claimed[t] = f"c:{tag}"
        try:
            expected, held = owner_slices(key, rec, st, defined_tags)
        except OwnershipError as exc:
            errors.append(str(exc))
            continue
        held_back += [(key, tag) for tag in held]
        if homelands is not None and key in homelands and creates and homes != homelands[key][1]:
            errors.append(f"s:{key}: add_homeland {homes} differs from state_homelands.json "
                          f"{homelands[key][1]} -- regenerate")
        got = sorted((t or "", sorted(p)) for t, p in creates)
        if got != sorted(expected):
            if not expected and creates:
                errors.append(f"s:{key}: emitted owner(s) {sorted({t for t, _ in got})} but the ownership map "
                              "gives no defined owner")
            elif {t for t, _ in got} != {t for t, _ in expected}:
                errors.append(f"s:{key}: emitted owner(s) {sorted({t for t, _ in got})} differ from "
                              f"state_ownership.json {sorted({t for t, _ in expected})} -- regenerate")
            else:
                errors.append(f"s:{key}: owned_provinces differ from state_ownership.json "
                              "(missing or extra provinces) -- regenerate")
    return errors, held_back
