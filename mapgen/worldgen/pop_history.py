"""Starting pops as game script: ``common/history/pops/NN_*.txt`` and
``common/history/population/NN_*.txt``.

Hand-authored inputs (``mapgen/config/pop_history/``) say how many people each
start tag has (``calibration.json``), how that total spreads over the tag's
states (``distribution.json`` + the derived ``state_weights.json``), which
cultures and faiths live in each state (``state_overrides.json``) and how rich /
literate each country starts (``population.json``). This module turns them into
the vanilla history shape::

    POPS = {
    	s:STATE_X = {
    		region_state:TAG = {
    			create_pop = { culture = <cu> size = <n> }
    			create_pop = { culture = <cu> religion = <rel> size = <n> }
    			create_pop = { pop_type = <pt> culture = <cu> size = <n> }
    		}
    	}
    }
    POPULATION = {
    	c:TAG ?= {
    		effect_starting_pop_wealth_<level> = yes
    		effect_starting_pop_literacy_<level> = yes
    	}
    }

Rules
-----
* The (state, owner) pairs come from the emitted ``common/history/states`` files,
  never from the ownership JSON, so a pair is only written when the game will
  actually have that ``region_state``. Owners the ownership map names but that
  have no country definition are reported as skipped.
* Every integer is exact: a tag's calibration total is split over its states by
  largest remainder (weights are integers / :class:`~fractions.Fraction`), each
  state's allotment over its mix likewise. ``emitted + skipped + dropped ==
  allotment`` for every state, and the allotments of a tag sum to its total.
* A culture, religion or pop type that does not resolve in this mod is skipped
  and reported (never emitted); ``slaves`` is emitted only where the owner's
  slavery law (``mapgen/config/country_history``) allows it and that data is
  present. A pop under ``min_pop_size`` is dropped and reported.
* ``UNO`` (the owner of unowned and out-of-scope land, #6391) is not a start nation
  and has no calibration total. Each (state, ``UNO``) pair instead gets one fixed
  pop, ``calibration.json`` ``unclaimed_pop`` (``culture``, ``size``; #6395), so no
  owned state starts empty; it gets a ``POPULATION`` entry like any owner. These
  people are reported on their own line, outside the calibrated tag totals, and a
  culture that does not resolve or a size under ``min_pop_size`` is a hard error.
* Output is sorted (state key, owner tag, size descending) and byte-stable.

Pure and deterministic: no clock, no randomness, no filesystem beyond the paths
handed in (the optional ``refresh_weights`` reads the province bitmap and arable
heatmap and needs numpy/Pillow).
"""

from __future__ import annotations

