@dataclass
class Config:
    scale: int
    min_pop: int
    totals: dict[str, int]                 # tag -> game total
    calib: dict[str, dict]                 # tag -> {canon, source, why, confidence}
    floor_permille: int
    city_boost: Fraction
    canon_city_boost: Fraction
    dist_overrides: list[dict]
    tag_mixes: dict[str, list[dict]]
    state_mixes: list[dict]
    population: dict[str, dict]            # tag -> {wealth, literacy, source, why}
    weights: dict[str, dict]               # state key -> {area_px, arable_milli, cities, canon_cities}
    unclaimed: dict | None = None          # calibration.json unclaimed_pop: {culture, size, source, why}


def _need(d: dict, keys: tuple[str, ...], where: str) -> None:
    for k in keys:
        if k not in d or d[k] in ("", None):
            raise PopHistoryError(f"{where}: missing '{k}'")


def _expand_groups(doc: dict, fields: tuple[str, ...], where: str) -> dict[str, dict]:
    """Merge a ``tags`` object and a ``groups`` list into ``{tag: entry}``."""
    out: dict[str, dict] = {}

    def put(tag: str, entry: dict) -> None:
        if tag in out:
            raise PopHistoryError(f"{where}: tag {tag} listed twice")
        out[tag] = entry

    for tag, e in doc.get("tags", {}).items():
        _need(e, fields, f"{where} {tag}")
        put(tag, e)
    for n, g in enumerate(doc.get("groups", [])):
        _need(g, fields + ("tags",), f"{where} group {n}")
        for tag in g["tags"]:
            put(tag, g)
    return out


def load_config(config_dir: Path) -> Config:
    d = Path(config_dir)

    def rd(name: str) -> dict:
        p = d / name
        if not p.exists():
            raise PopHistoryError(f"missing {p}")
        return json.loads(p.read_text(encoding="utf-8"))

    cal = rd("calibration.json")
    scale = cal.get("scale_factor")
    if not isinstance(scale, int) or scale < 1:
        raise PopHistoryError("calibration.json: scale_factor must be a positive integer")
    min_pop = cal.get("min_pop_size")
    if not isinstance(min_pop, int) or min_pop < 1:
        raise PopHistoryError("calibration.json: min_pop_size must be a positive integer")
    calib = _expand_groups(cal, ("canon", "source", "why", "confidence"), "calibration.json")
    totals = {}
    for tag, e in calib.items():
        if not isinstance(e["canon"], int) or e["canon"] < 0:
            raise PopHistoryError(f"calibration.json {tag}: canon must be a non-negative integer")
        if e["confidence"] not in CONFIDENCES:
            raise PopHistoryError(f"calibration.json {tag}: confidence must be one of {CONFIDENCES}")
        totals[tag] = e["canon"] * scale
    if sh.UNO_TAG in calib:
        raise PopHistoryError(f"calibration.json: c:{sh.UNO_TAG} takes no calibration total; "
                              "its per-state pop is 'unclaimed_pop'")
    unclaimed = cal.get("unclaimed_pop")
    if unclaimed is not None:
        _need(unclaimed, ("culture", "size", "source", "why"), "calibration.json unclaimed_pop")
        if not isinstance(unclaimed["size"], int) or isinstance(unclaimed["size"], bool) or unclaimed["size"] < min_pop:
            raise PopHistoryError(f"calibration.json unclaimed_pop: size must be an integer >= min_pop_size ({min_pop})")

    dist = rd("distribution.json")
    ovr = dist.get("overrides", [])
    for n, o in enumerate(ovr):
        _need(o, ("key", "anchor", "source", "why"), f"distribution.json override {n}")
        if ("multiplier" in o) == ("share" in o):
            raise PopHistoryError(f"distribution.json {o['key']}: give exactly one of 'multiplier' or 'share'")

    so = rd("state_overrides.json")
    tag_mixes = {}
    for tag, e in so.get("tags", {}).items():
        _need(e, ("mix",), f"state_overrides.json tags.{tag}")
        tag_mixes[tag] = e["mix"]
    states = so.get("states", [])
    for n, e in enumerate(states):
        _need(e, ("key", "anchor", "mode", "mix"), f"state_overrides.json state {n}")
        if e["mode"] not in ("add", "replace"):
            raise PopHistoryError(f"state_overrides.json {e['key']}: mode must be 'add' or 'replace'")

    pop = _expand_groups(rd("population.json"), ("wealth", "literacy", "source", "why"), "population.json")
    for tag, e in pop.items():
        if e["wealth"] not in WEALTH_LEVELS:
            raise PopHistoryError(f"population.json {tag}: wealth '{e['wealth']}' not in {WEALTH_LEVELS}")
        if e["literacy"] not in LITERACY_LEVELS:
            raise PopHistoryError(f"population.json {tag}: literacy '{e['literacy']}' not in {LITERACY_LEVELS}")

    w = rd("state_weights.json")
    return Config(
        scale=scale, min_pop=min_pop, totals=totals, calib=calib,
        floor_permille=int(dist.get("floor_permille", 50)),
        city_boost=frac(dist.get("city_boost", "0"), "distribution.json city_boost"),
        canon_city_boost=frac(dist.get("canon_city_boost", "0"), "distribution.json canon_city_boost"),
        dist_overrides=ovr, tag_mixes=tag_mixes, state_mixes=states, population=pop,
        weights=w.get("states", {}), unclaimed=unclaimed,
    )


@dataclass
class World:
    """Everything read from the mod tree, so the fixture can point it elsewhere."""
    states_by_file: dict[str, list]            # map_data/state_regions
    ownership: dict                            # state_ownership.json
    history: dict[str, list]                   # state-history file -> parse_history_text()
    countries: dict[str, Country]
    cultures: dict[str, str | None]
    religions: set[str]
    pop_types: set[str]
    slavery: dict[str, str] | None             # None: country_history data absent
    homelands: dict[str, list[str]] = field(default_factory=dict)   # state key -> add_homeland culture ids
    tech_tier: dict[str, int] | None = None


