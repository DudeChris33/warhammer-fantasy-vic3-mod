def _pop_line(p: Pop) -> str:
    parts = []
    if p.pop_type:
        parts.append(f"pop_type = {p.pop_type}")
    parts.append(f"culture = {p.culture}")
    if p.religion:
        parts.append(f"religion = {p.religion}")
    parts.append(f"size = {p.size}")
    return f"\t\t\tcreate_pop = {{ {' '.join(parts)} }}"


def render_pops(units: list[Unit]) -> str:
    """One pops file (no BOM, LF). Header only when no unit has a pop to emit."""
    units = [u for u in units if u.pops]
    if not units:
        return HEADER_POPS
    lines = [HEADER_POPS.rstrip("\n"), "POPS = {"]
    cur = None
    for u in sorted(units, key=lambda u: (u.key, u.tag)):
        if u.key != cur:
            if cur is not None:
                lines.append("\t}")
            lines.append(f"\ts:{u.key} = {{")
            cur = u.key
        lines.append(f"\t\tregion_state:{u.tag} = {{")
        lines += [_pop_line(p) for p in u.pops]
        lines.append("\t\t}")
    lines += ["\t}", "}"]
    return "\n".join(lines) + "\n"


def render_population(entries: list[tuple[str, dict]]) -> str:
    if not entries:
        return HEADER_POPULATION
    lines = [HEADER_POPULATION.rstrip("\n"), "POPULATION = {"]
    for tag, e in sorted(entries):
        lines += [f"\tc:{tag} ?= {{",
                  f"\t\teffect_starting_pop_wealth_{e['wealth']} = yes",
                  f"\t\teffect_starting_pop_literacy_{e['literacy']} = yes",
                  "\t}"]
    lines.append("}")
    return "\n".join(lines) + "\n"


def render_all(p: Plan) -> tuple[dict[str, str], dict[str, str]]:
    return ({f: render_pops(us) for f, us in p.files.items()},
            {f: render_population(es) for f, es in p.population.items()})


_POP_BLOCK = re.compile(r"\bcreate_pop\s*=\s*\{([^}]*)\}")
_REGION_STATE = re.compile(r"\bregion_state:(\w+)\s*=\s*\{")
_STATE_SCOPE = re.compile(r"\bs:(STATE_\w+)\s*=\s*\{")


def parse_pops_text(text: str) -> list[tuple[str, list[tuple[str, list[dict]]]]]:
    """``[(state key, [(tag, [pop fields])])]`` in file order."""
    text = sh._strip_comments(text.lstrip("﻿"))
    out = []
    idx = 0
    while True:
        m = _STATE_SCOPE.search(text, idx)
        if not m:
            return out
        o = text.index("{", m.end() - 1)
        c = sh._match_brace(text, o)
        body = text[o + 1:c]
        regions = []
        j = 0
        while True:
            rm = _REGION_STATE.search(body, j)
            if not rm:
                break
            ro = body.index("{", rm.end() - 1)
            rc = sh._match_brace(body, ro)
            pops = []
            for pm in _POP_BLOCK.finditer(body[ro + 1:rc]):
                fields = dict(re.findall(r"(\w+)\s*=\s*(\S+)", pm.group(1)))
                pops.append(fields)
            regions.append((rm.group(1), pops))
            j = rc + 1
        out.append((m.group(1), regions))
        idx = c + 1


