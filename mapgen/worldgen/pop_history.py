HEADER_POPS = ("# GENERATED by mapgen/generate_pop_history.py from mapgen/config/pop_history/*.json"
               " - never hand-edit; edit the JSON inputs and regenerate.\n")
HEADER_POPULATION = HEADER_POPS

WEALTH_LEVELS = ("very_high", "high", "medium", "low")
LITERACY_LEVELS = ("very_high", "high", "middling", "low", "very_low", "baseline")
CONFIDENCES = ("high", "medium", "low")
SLAVERY_BANNED = "law_slavery_banned"


class PopHistoryError(ValueError):
    """An input that cannot be used as given (always a hard error)."""


# ---------------------------------------------------------------------------
# Exact arithmetic
# ---------------------------------------------------------------------------

def frac(value, where: str) -> Fraction:
    """A JSON number or numeric string as an exact Fraction (never via float
    arithmetic: ``0.1`` becomes 1/10)."""
    if isinstance(value, bool) or not isinstance(value, (int, float, str)):
        raise PopHistoryError(f"{where}: expected a number, got {value!r}")
    try:
        return Fraction(str(value))
    except (ValueError, ZeroDivisionError):
        raise PopHistoryError(f"{where}: {value!r} is not a number") from None


def largest_remainder(total: int, weights: list[Fraction]) -> list[int]:
    """Split integer ``total`` proportionally to ``weights``: floor quotas, then
    the leftover units go to the largest fractional remainders, ties to the
    lower index. Always sums to ``total`` exactly."""
    if total < 0:
        raise PopHistoryError(f"cannot split a negative total {total}")
    s = sum(weights, Fraction(0))
    if s <= 0:
        raise PopHistoryError("cannot split over weights that sum to 0")
    quotas = [Fraction(total) * w / s for w in weights]
    out = [int(q) for q in quotas]  # floor: quotas are non-negative
    left = total - sum(out)
    order = sorted(range(len(weights)), key=lambda i: (-(quotas[i] - out[i]), i))
    for i in order[:left]:
        out[i] += 1
    return out


# ---------------------------------------------------------------------------
# Script parsing (country definitions, cultures, religions, pop types)
# ---------------------------------------------------------------------------

def top_level_blocks(text: str) -> list[tuple[str, str]]:
    """``[(name, body)]`` for every top-level ``name = { ... }`` of a script file."""
    text = sh._strip_comments(text.lstrip("﻿"))
    out = []
    i = 0
    pat = re.compile(r"(?m)^([A-Za-z_][\w.]*)\s*=\s*\{")
    while True:
        m = pat.search(text, i)
        if not m:
            return out
        open_idx = text.index("{", m.end() - 1)
        close_idx = sh._match_brace(text, open_idx)
        out.append((m.group(1), text[open_idx + 1:close_idx]))
        i = close_idx + 1


@dataclass(frozen=True)
class Country:
    tag: str
    stem: str                 # NN_<region> of its country_definitions file
    cultures: tuple[str, ...]


def load_countries(country_defs_dir: Path) -> dict[str, Country]:
    out: dict[str, Country] = {}
    for path in sorted(Path(country_defs_dir).glob("*.txt")):
        for name, body in top_level_blocks(path.read_text(encoding="utf-8-sig")):
            if not re.fullmatch(r"[A-Z][A-Z0-9]{2}", name) or sh._DYNAMIC.search(body):
                continue
            m = re.search(r"\bcultures\s*=\s*\{([^}]*)\}", body)
            out[name] = Country(name, path.stem, tuple(m.group(1).split()) if m else ())
    return out


def load_cultures(cultures_dir: Path) -> dict[str, str | None]:
    """``{culture id: default religion id}`` over ``common/cultures/*.txt``."""
    out: dict[str, str | None] = {}
    for path in sorted(Path(cultures_dir).glob("*.txt")):
        for name, body in top_level_blocks(path.read_text(encoding="utf-8-sig")):
            m = re.search(r"(?m)^\s*religion\s*=\s*(\w+)", body)
            out[name] = m.group(1) if m else None
    return out


def load_ids(path_or_dir: Path) -> set[str]:
    """Top-level ids of one script file, or of every ``*.txt`` in a folder."""
    p = Path(path_or_dir)
    files = sorted(p.glob("*.txt")) if p.is_dir() else [p]
    return {n for f in files for n, _ in top_level_blocks(f.read_text(encoding="utf-8-sig"))}


def load_slavery(country_history_dir: Path | None) -> dict[str, str] | None:
    """``{tag: slavery law}`` from ``mapgen/config/country_history/*.json`` (baseline
    <- profile <- tag), or ``None`` when that data is not in the tree."""
    if country_history_dir is None or not Path(country_history_dir).is_dir():
        return None
    files = sorted(Path(country_history_dir).glob("*.json"))
    if not files:
        return None
    out: dict[str, str] = {}
    for f in files:
        d = json.loads(f.read_text(encoding="utf-8"))
        for tag, v in d.get("tags", {}).items():
            prof = d.get("profiles", {}).get(v.get("profile"), {})
            laws = {**d.get("baseline", {}).get("laws", {}), **prof.get("laws", {}), **v.get("laws", {})}
            out[tag] = laws.get("lawgroup_slavery", SLAVERY_BANNED)
    return out


