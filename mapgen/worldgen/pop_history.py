@dataclass
class Pop:
    culture: str
    size: int
    religion: str | None = None
    pop_type: str | None = None


@dataclass
class Unit:
    """One (state, owner) pair the game creates."""
    key: str
    tag: str
    fname: str
    weight: Fraction = Fraction(0)
    allot: int = 0
    pops: list[Pop] = field(default_factory=list)
    skipped: list[tuple[Pop, str]] = field(default_factory=list)   # (pop, reason)
    dropped: list[Pop] = field(default_factory=list)


@dataclass
class Plan:
    units: list[Unit]
    files: dict[str, list[Unit]]               # pops file -> units (sorted)
    population: dict[str, list[tuple[str, dict]]]   # population file -> [(tag, entry)]
    skipped_owners: list[tuple[str, str]]      # (state key, tag): owner has no definition
    unowned_overrides: list[str]
    warnings: list[str]


def _anchors(world: World) -> dict[str, list[int]]:
    return {k: v.get("naming_anchor") for k, v in world.ownership["states"].items()}


def _check_anchor(item: dict, anchors: dict, where: str) -> None:
    key = item["key"]
    if key not in anchors:
        raise PopHistoryError(f"{where}: {key} is not a state in state_ownership.json / map_data")
    if list(item["anchor"]) != list(anchors[key]):
        raise PopHistoryError(f"{where}: {key} anchor {list(item['anchor'])} no longer matches the state's "
                              f"naming anchor {list(anchors[key])} -- the state was renamed or re-cut; "
                              "re-anchor the override")


def _discover_units(world: World) -> tuple[list[Unit], list[tuple[str, str]], dict[str, Fraction]]:
    """(state, owner) pairs from the emitted state history, the owners skipped for
    lack of a definition, and each unit's share of its state (provinces owned /
    provinces of the state)."""
    land = {s.key: s for ss in world.states_by_file.values() for s in ss}
    file_of = {s.key: f for f, ss in world.states_by_file.items() for s in ss}
    units: list[Unit] = []
    share: dict[str, Fraction] = {}
    seen: set[tuple[str, str]] = set()
    for hname in sorted(world.history):
        for key, creates in world.history[hname]:
            if key not in land:
                raise PopHistoryError(f"history/states/{hname}: s:{key} is not a land state in map_data")
            for tag, provs in creates:
                # UNO (unclaimed / out-of-scope land) is a unit too; plan() gives it the
                # fixed unclaimed_pop instead of a calibrated share
                if tag is None or (key, tag) in seen:
                    raise PopHistoryError(f"history/states/{hname} s:{key}: bad or duplicate create_state")
                seen.add((key, tag))
                u = Unit(key, tag, file_of[key])
                units.append(u)
                share[f"{key}|{tag}"] = Fraction(len(provs), max(1, len(land[key].provinces)))
    units.sort(key=lambda u: (u.key, u.tag))
    skipped: list[tuple[str, str]] = []
    for key, rec in sorted(world.ownership["states"].items()):
        if rec.get("scope") != "drawn":
            continue
        owners = [rec["owner"]] if "owner" in rec else [o["owner"] for o in rec.get("owners", [])]
        for o in owners:
            if o in ("unowned", "placeholder") or (key, o) in seen:
                continue
            if o not in world.countries:
                skipped.append((key, o))
    return units, sorted(skipped), share


def _mix_shares(unit: Unit, cfg: Config, world: World, override: dict | None) -> list[tuple[dict, Fraction]]:
    """``[(entry, percent)]`` summing to exactly 100 for one (state, owner)."""
    where = f"{unit.key}/{unit.tag}"
    if unit.tag in cfg.tag_mixes:
        base_entries = cfg.tag_mixes[unit.tag]
        base = [(e, frac(e["share"], f"tags.{unit.tag}.mix share")) for e in base_entries]
        if sum(p for _, p in base) != 100:
            raise PopHistoryError(f"state_overrides.json tags.{unit.tag}.mix: shares sum to "
                                  f"{float(sum(p for _, p in base))}, not 100")
    else:
        primary = world.countries[unit.tag].cultures
        homes = world.homelands.get(unit.key) or list(primary)
        if not homes:
            raise PopHistoryError(f"c:{unit.tag} has no homelands or primary cultures and no tags.{unit.tag}.mix")
        # the state's homelands, the owner's primary cultures counting double
        wts = [Fraction(2 if c in primary else 1) for c in homes]
        base = [({"culture": c}, 100 * w / sum(wts)) for c, w in zip(homes, wts)]
    if override is None:
        return base
    mix = [(e, frac(e["share"], f"{where} mix share")) for e in override["mix"]]
    for e, _ in mix:
        _need(e, ("culture", "share", "source", "why"), f"state_overrides.json {where}")
    total = sum(p for _, p in mix)
    if override["mode"] == "replace":
        if total != 100:
            raise PopHistoryError(f"state_overrides.json {where} (replace): shares sum to {float(total)}%, not 100%")
        return mix
    if not 0 < total < 100:
        raise PopHistoryError(f"state_overrides.json {where} (add): minority shares sum to {float(total)}%, "
                              "must be above 0 and below 100")
    keep = (100 - total) / 100
    return [(e, p * keep) for e, p in base] + mix


def plan(cfg: Config, world: World) -> Plan:
    anchors = _anchors(world)
    for n, o in enumerate(cfg.dist_overrides):
        _check_anchor(o, anchors, f"distribution.json override {n}")
    for n, o in enumerate(cfg.state_mixes):
        _check_anchor(o, anchors, f"state_overrides.json state {n}")

    all_units, skipped_owners, share = _discover_units(world)
    # UNO units take the fixed unclaimed_pop below and are invisible to every
    # calibrated step (distribution, overrides, mixes, tag totals)
    units = [u for u in all_units if u.tag != sh.UNO_TAG]
    uno_units = [u for u in all_units if u.tag == sh.UNO_TAG]
    warnings: list[str] = []
    unowned: list[str] = []

    def find(o: dict, where: str) -> list[Unit]:
        hits = [u for u in units if u.key == o["key"] and ("tag" not in o or u.tag == o["tag"])]
        if not hits:
            unowned.append(o["key"])
            warnings.append(f"{where}: {o['key']} has no emitted (state, owner) pair; override unused")
        elif len(hits) > 1 and "tag" not in o:
            raise PopHistoryError(f"{where}: {o['key']} is split between {[u.tag for u in hits]}; add a 'tag'")
        return hits

    # --- distribution ---------------------------------------------------
    mult: dict[tuple[str, str], Fraction] = {}
    fixed: dict[tuple[str, str], Fraction] = {}
    for n, o in enumerate(cfg.dist_overrides):
        for u in find(o, f"distribution.json override {n}"):
            k = (u.key, u.tag)
            if k in mult or k in fixed:
                raise PopHistoryError(f"distribution.json: {u.key}/{u.tag} has two overrides")
            if "multiplier" in o:
                m = frac(o["multiplier"], f"distribution.json {u.key} multiplier")
                if m <= 0:
                    raise PopHistoryError(f"distribution.json {u.key}: multiplier must be positive")
                mult[k] = m
            else:
                s = frac(o["share"], f"distribution.json {u.key} share")
                if not 0 < s < 1:
                    raise PopHistoryError(f"distribution.json {u.key}: share must be between 0 and 1")
                fixed[k] = s

    for u in units:
        w = cfg.weights.get(u.key)
        if w is None:
            raise PopHistoryError(f"state_weights.json has no entry for {u.key} -- run "
                                  "generate_pop_history.py --refresh-weights")
        base = Fraction(w["arable_milli"] + cfg.floor_permille * w["area_px"])
        boost = 1 + cfg.city_boost * w.get("cities", 0) + cfg.canon_city_boost * len(w.get("canon_cities", []))
        u.weight = base * boost * mult.get((u.key, u.tag), 1) * share[f"{u.key}|{u.tag}"]

    tag_units: dict[str, list[Unit]] = {}
    for u in units:
        tag_units.setdefault(u.tag, []).append(u)
    for tag in sorted(tag_units):
        if tag not in cfg.totals:
            raise PopHistoryError(f"c:{tag} owns {len(tag_units[tag])} state(s) but has no calibration.json entry")
        total = cfg.totals[tag]
        us = tag_units[tag]
        fx = [u for u in us if (u.key, u.tag) in fixed]
        free = [u for u in us if (u.key, u.tag) not in fixed]
        fsum = sum((fixed[(u.key, u.tag)] for u in fx), Fraction(0))
        if (free and fsum >= 1) or (not free and fsum != 1):
            raise PopHistoryError(f"distribution.json {tag}: fixed shares sum to {float(fsum)} "
                                  f"({'must stay below 1 while other states remain' if free else 'must be exactly 1'})")
        # fixed units take their share of the total; the rest split what is left
        if free:
            weights = [fixed[(u.key, u.tag)] for u in fx] + [
                (1 - fsum) * u.weight / sum((x.weight for x in free), Fraction(0)) for u in free]
        else:
            weights = [fixed[(u.key, u.tag)] for u in fx]
        order = fx + free
        for u, a in zip(order, largest_remainder(total, weights)):
            u.allot = a
    for tag in cfg.totals:
        if tag not in tag_units and tag in world.countries:
            warnings.append(f"calibration.json: c:{tag} has a total but owns no emitted state")

    # --- mix ------------------------------------------------------------
    smix: dict[tuple[str, str], dict] = {}
    for n, o in enumerate(cfg.state_mixes):
        for u in find(o, f"state_overrides.json state {n}"):
            if (u.key, u.tag) in smix:
                raise PopHistoryError(f"state_overrides.json: {u.key}/{u.tag} has two overrides")
            smix[(u.key, u.tag)] = o
    slavery = world.slavery
    for u in units:
        entries = _mix_shares(u, cfg, world, smix.get((u.key, u.tag)))
        sizes = largest_remainder(u.allot, [p for _, p in entries]) if u.allot else [0] * len(entries)
        merged: dict[tuple, Pop] = {}
        for (e, _), size in zip(entries, sizes):
            cu, rel, pt = e["culture"], e.get("religion"), e.get("pop_type")
            reason = None
            if cu not in world.cultures:
                reason = f"culture '{cu}' is not defined in this mod"
            elif rel is not None and rel not in world.religions:
                reason = f"religion '{rel}' is not defined in this mod"
            elif pt is not None and pt not in world.pop_types:
                reason = f"pop type '{pt}' is not defined in this mod"
            elif pt == "slaves":
                if slavery is None:
                    reason = "pop type 'slaves' needs the owner's slavery law (mapgen/config/country_history absent)"
                elif slavery.get(u.tag, SLAVERY_BANNED) == SLAVERY_BANNED:
                    raise PopHistoryError(f"{u.key}/{u.tag}: 'slaves' pop but c:{u.tag} has {SLAVERY_BANNED}")
            if reason is None and rel is not None and rel == world.cultures[cu]:
                rel = None   # the culture's default faith is implied
            k = (cu, rel, pt)
            if reason:
                u.skipped.append((Pop(cu, size, rel, pt), reason))
            elif k in merged:
                merged[k].size += size
            else:
                merged[k] = Pop(cu, size, rel, pt)
        for p in merged.values():
            if p.size == 0:
                continue
            (u.dropped if p.size < cfg.min_pop else u.pops).append(p)
        u.pops.sort(key=lambda p: (-p.size, p.culture, p.religion or "", p.pop_type or ""))
        u.dropped.sort(key=lambda p: (p.culture, p.religion or "", p.pop_type or ""))

    # --- unclaimed land (UNO): one fixed pop per state, outside calibration ---
    if uno_units:
        uc = cfg.unclaimed
        if uc is None:
            raise PopHistoryError(f"c:{sh.UNO_TAG} owns {len(uno_units)} state(s) but calibration.json has no "
                                  "'unclaimed_pop' (culture, size, source, why)")
        if uc["culture"] not in world.cultures:
            raise PopHistoryError(f"calibration.json unclaimed_pop: culture '{uc['culture']}' is not defined in this mod")
        for u in uno_units:
            u.allot = uc["size"]
            u.pops = [Pop(uc["culture"], uc["size"])]   # the culture's default faith is implied
        tag_units[sh.UNO_TAG] = uno_units
    elif cfg.unclaimed is not None:
        warnings.append(f"calibration.json: unclaimed_pop is set but c:{sh.UNO_TAG} owns no emitted state")
    units = sorted(units + uno_units, key=lambda u: (u.key, u.tag))

    # --- files -----------------------------------------------------------
    files: dict[str, list[Unit]] = {f: [] for f in sorted(world.states_by_file)}
    for u in units:
        files[u.fname].append(u)

    stems = {f[:-4] for f in world.states_by_file}
    population: dict[str, list[tuple[str, dict]]] = {f: [] for f in sorted(world.states_by_file)}
    for tag in sorted(tag_units):
        if tag not in cfg.population:
            raise PopHistoryError(f"c:{tag} owns states but has no population.json entry")
        stem = world.countries[tag].stem
        fname = stem + ".txt" if stem in stems else tag_units[tag][0].fname
        population[fname].append((tag, cfg.population[tag]))
        if world.tech_tier is not None and tag in world.tech_tier:
            _tier_warning(tag, world.tech_tier[tag], cfg.population[tag], warnings)
    for tag in cfg.population:
        if tag not in tag_units:
            warnings.append(f"population.json: c:{tag} owns no emitted state; entry unused")
    return Plan(units, files, population, skipped_owners, sorted(set(unowned)), warnings)


#: literacy bands per tech tier (a warning, not an error: a deliberate exception carries a why)
TIER_LITERACY = {1: {"very_high", "high"}, 2: {"very_high", "high"}, 3: {"high", "middling"},
                 4: {"high", "middling", "low"}, 5: {"middling", "low"}, 6: {"low", "very_low"},
                 7: {"very_low", "baseline"}}


def _tier_warning(tag: str, tier: int, entry: dict, warnings: list[str]) -> None:
    allowed = TIER_LITERACY.get(tier)
    if allowed and entry["literacy"] not in allowed:
        warnings.append(f"population.json: c:{tag} literacy '{entry['literacy']}' is outside the usual band "
                        f"{sorted(allowed)} for tech tier {tier}")


