def check_texts(pops_texts: dict[str, str], population_texts: dict[str, str], world: World) -> list[str]:
    """Resolve every s:, region_state:, c:, culture, religion and pop_type of the
    emitted files; braces balance; every pair exists in ``common/history/states``
    and every pair that file creates for a defined country has at least one pop."""
    errors: list[str] = []
    land = {s.key: s for ss in world.states_by_file.values() for s in ss}
    file_of = {s.key: f for f, ss in world.states_by_file.items() for s in ss}
    created = {(k, t) for ents in world.history.values() for k, cs in ents for t, _ in cs}
    for fname in sorted(world.states_by_file):
        for label, texts in (("pops", pops_texts), ("population", population_texts)):
            if fname not in texts:
                errors.append(f"history/{label}/{fname} is missing -- run generate_pop_history.py")
    for label, texts in (("pops", pops_texts), ("population", population_texts)):
        for fname in sorted(texts):
            t = sh._strip_comments(texts[fname])
            if t.count("{") != t.count("}"):
                errors.append(f"history/{label}/{fname}: braces do not balance")
            if fname not in world.states_by_file:
                errors.append(f"history/{label}/{fname}: no map_data/state_regions/{fname} counterpart")
    seen: set[str] = set()
    populated: set[tuple[str, str]] = set()
    for fname in sorted(pops_texts):
        try:
            parsed = parse_pops_text(pops_texts[fname])
        except sh.OwnershipError as exc:
            errors.append(f"history/pops/{fname}: {exc}")
            continue
        for key, regions in parsed:
            where = f"history/pops/{fname} s:{key}"
            if key not in land:
                errors.append(f"{where}: not a land state in map_data")
            elif file_of[key] != fname:
                errors.append(f"{where}: belongs in {file_of[key]}")
            if key in seen:
                errors.append(f"{where}: state appears more than once")
            seen.add(key)
            for tag, pops in regions:
                if (key, tag) not in created:
                    errors.append(f"{where}: region_state:{tag} is not created by common/history/states")
                if tag not in world.countries:
                    errors.append(f"{where}: c:{tag} has no country definition")
                if not pops:
                    errors.append(f"{where} region_state:{tag}: no create_pop")
                else:
                    populated.add((key, tag))
                for f in pops:
                    bad = set(f) - {"culture", "religion", "pop_type", "size"}
                    if bad:
                        errors.append(f"{where}/{tag}: unknown create_pop field(s) {sorted(bad)}")
                    if f.get("culture") not in world.cultures:
                        errors.append(f"{where}/{tag}: culture {f.get('culture')} does not resolve")
                    if "religion" in f and f["religion"] not in world.religions:
                        errors.append(f"{where}/{tag}: religion {f['religion']} does not resolve")
                    if "pop_type" in f and f["pop_type"] not in world.pop_types:
                        errors.append(f"{where}/{tag}: pop_type {f['pop_type']} does not resolve")
                    if not f.get("size", "").isdigit() or int(f["size"]) < 1:
                        errors.append(f"{where}/{tag}: size {f.get('size')} is not a positive integer")
    # the reverse direction: every region_state the game creates starts with people
    # (an empty one, UNO's included, is the "There are no pops" load class, #6395)
    for key, tag in sorted(created - populated):
        if tag is not None and tag in world.countries:
            errors.append(f"history/pops/{file_of.get(key, '?')} s:{key}: region_state:{tag} is created by "
                          "common/history/states but has no create_pop")
    for fname in sorted(population_texts):
        t = sh._strip_comments(population_texts[fname])
        for tag, body in re.findall(r"\bc:(\w+)\s*\?=\s*\{([^}]*)\}", t):
            if tag not in world.countries:
                errors.append(f"history/population/{fname}: c:{tag} has no country definition")
            w = re.findall(r"effect_starting_pop_wealth_(\w+)\s*=\s*yes", body)
            lt = re.findall(r"effect_starting_pop_literacy_(\w+)\s*=\s*yes", body)
            if len(w) != 1 or w[0] not in WEALTH_LEVELS or len(lt) != 1 or lt[0] not in LITERACY_LEVELS:
                errors.append(f"history/population/{fname}: c:{tag} needs exactly one valid wealth and literacy effect")
    return errors


