# Derived weights (needs numpy / Pillow; the only image-reading step)
# ---------------------------------------------------------------------------

def refresh_weights(provinces_png: Path, arable_png: Path, states_by_file: dict[str, list],
                    hub_worksheet: Path, canon_cities: Path) -> dict:
    """``state_weights.json`` content: per land state, province pixel area, the
    arable heatmap summed over it (milli-units, so the weight stays integer), the
    count of named ``city`` hubs and the canon cities whose anchor lies in it."""
    import numpy as np
    from PIL import Image

    Image.MAX_IMAGE_PIXELS = None
    p = np.asarray(Image.open(provinces_png).convert("RGB")).astype(np.uint32)
    code2d = (p[..., 0] << 16) | (p[..., 1] << 8) | p[..., 2]
    code = code2d.ravel()
    a = np.asarray(Image.open(arable_png)).astype(np.float64).ravel()
    scale = 65535.0 if a.max() > 1.0 else 1.0
    u, inv = np.unique(code, return_inverse=True)
    cnt = np.bincount(inv)
    mass = np.bincount(inv, weights=a / scale)
    prov = {f"x{int(c):06X}": (int(n), float(m)) for c, n, m in zip(u, cnt, mass)}
    state_of = {t: s.key for ss in states_by_file.values() for s in ss for t in s.provinces}
    h, w = p.shape[:2]

    def state_at(xy) -> str | None:
        x, y = int(xy[0]), int(xy[1])
        if not (0 <= x < w and 0 <= y < h):
            return None
        c = int(code2d[y, x])
        return state_of.get(f"x{c:06X}")

    out = {s.key: {"area_px": 0, "arable_milli": 0, "cities": 0, "canon_cities": []}
           for ss in states_by_file.values() for s in ss}
    for s in (s for ss in states_by_file.values() for s in ss):
        for t in s.provinces:
            n, m = prov.get(t, (0, 0.0))
            out[s.key]["area_px"] += n
            out[s.key]["arable_milli"] += int(round(m * 1000))
    for row in json.loads(Path(hub_worksheet).read_text(encoding="utf-8"))["hubs"]:
        if row.get("hub") == "city" and not row.get("stack_on"):
            k = state_at(row["anchor"])
            if k in out:
                out[k]["cities"] += 1
    for row in json.loads(Path(canon_cities).read_text(encoding="utf-8"))["cities"]:
        k = state_at(row["anchor"])
        if k in out:
            out[k]["canon_cities"].append(row["name"])
    for v in out.values():
        v["canon_cities"].sort()
    return {"_comment": "GENERATED by mapgen/generate_pop_history.py --refresh-weights from map_data/provinces.png, "
                        "mapgen/derived/arable_heatmap.png, hub_worksheet.json and canon_cities.json. Never hand-edit. "
                        "area_px = province pixels; arable_milli = sum of the arable heatmap (0..1) over the state x 1000; "
                        "cities = named city hubs; canon_cities = canon_cities.json rows inside.",
            "states": {k: out[k] for k in sorted(out)}}
