def _ownership_mode(b: Building, laws: frozenset[str], resolved: bool) -> str | None:
    """The private owner building for ``b`` (or None = country-owned), from the tag's starting laws.
    Matches vanilla ``common/history/buildings``: resource buildings (farms, ranches, plantations, mines,
    logging) are owned by a manor house, industry (incl. shipyards) by a financial district; ports, trade
    centres, government, military and construction are country-owned. Vanilla never creates the owner
    buildings itself -- the game makes them from ``add_ownership``."""
    if b.ownership_type != "self" or not resolved:
        return None
    if b.file in RESOURCE_FILES:
        return None if "law_collectivized_agriculture" in laws else AGRI_OWNER
    if b.file == "01_industry.txt":
        return None if "law_command_economy" in laws else PRIVATE_OWNER
    return None


def _split(total: int, n: int) -> list[int]:
    return [total // n + (1 if i < total % n else 0) for i in range(n)] if n > 0 else []


def _check_override_keys(cfg: Config, world: World) -> None:
    for where, rows in (("state_overrides.json", cfg.overrides), ("blocked.json blocked_by_resources", cfg.blocked_res),
                        ("blocked.json blocked_by_tech", cfg.blocked_tech)):
        for n, o in enumerate(rows):
            k = o["key"]
            if k not in world.res:
                raise BuildingHistoryError(f"{where} {n}: {k} is not a state")
            if list(o["anchor"]) != list(world.anchors.get(k) or []):
                raise BuildingHistoryError(f"{where} {n}: {k} anchor {list(o['anchor'])} no longer matches the state's "
                                           f"naming anchor {world.anchors.get(k)} -- the state was renamed or re-cut; re-anchor the override")
            for b in ([o["building"]] if "building" in o else list(o.get("buildings", {}))):
                if b not in world.buildings:
                    raise BuildingHistoryError(f"{where} {n}: unknown building {b!r}")


def plan(cfg: Config, world: World) -> Plan:
    _check_override_keys(cfg, world)
    warnings: list[str] = []
    by_tag: dict[str, list[Unit]] = {}
    for key, tags in world.owners.items():
        for t in tags:
            by_tag.setdefault(t, []).append(Unit(key, t, world.pops.get((key, t), 0)))
    for t in sorted(by_tag):
        if t not in cfg.tags:
            raise BuildingHistoryError(f"c:{t} owns a state but has no profiles.json entry")
        if t not in world.known_tags:
            raise BuildingHistoryError(f"c:{t} has no non-dynamic country definition")
    for t in cfg.tags:
        if t not in by_tag:
            warnings.append(f"profiles.json has an entry for {t}, which owns no state")
    for o in cfg.overrides:
        for tag in ([o["owner"]] if o.get("owner") else world.owners.get(o["key"], [])):
            if tag not in world.owners.get(o["key"], []):
                raise BuildingHistoryError(f"state_overrides.json: {o['key']} is not owned by {tag} (owners: {world.owners.get(o['key'])})")
    for o in cfg.blocked_tech:
        ts = world.tags.get(o["tag"])
        need = [t for t in world.buildings[o["building"]].techs if ts is None or t not in ts.techs]
        if world.buildings[o["building"]].techs and not need:
            warnings.append(f"blocked_by_tech: {o['tag']} now has the techs for {o['building']} in {o['key']} -- move it to state_overrides.json")
    for o in cfg.blocked_res:
        r = world.res[o["key"]]
        b = world.buildings[o["building"]]
        have = o["building"] in r.arable or o["building"] in dict(r.capped)
        if have:
            warnings.append(f"blocked_by_resources: {o['key']} now has {o['building']} -- move it to state_overrides.json")
        elif b.file not in RESOURCE_FILES:
            raise BuildingHistoryError(f"blocked.json: {o['building']} is not a resource building")

    for tag in sorted(by_tag):
        units = sorted(by_tag[tag], key=lambda u: (-u.pop, u.key))
        ts = world.tags.get(tag) or TagState(frozenset(), frozenset(), False, "no country history block")
        prof = dict(cfg.archetypes[cfg.tags[tag]["archetype"]])
        prof.update(cfg.tags[tag].get("set", {}))
        _plan_tag(tag, units, ts, prof, cfg, world)
    files: dict[str, list[Unit]] = {f: [] for f in world.files}
    file_of = {k: f for f, ks in world.files.items() for k in ks}
    allu = [u for us in by_tag.values() for u in us]
    for u in sorted(allu, key=lambda u: (u.key, u.tag)):
        files[file_of[u.key]].append(u)
    return Plan(files, sorted(allu, key=lambda u: (u.key, u.tag)), warnings)


class _Ctx:
    def __init__(self, tag, ts, world, cfg):
        self.tag, self.ts, self.world, self.cfg = tag, ts, world, cfg


def _try_place(u: Unit, bid: str, levels: int, ctx: _Ctx, remaining: list[int], arable_left: dict, capped_left: dict,
               override: bool, why: str) -> None:
    """Place ``levels`` of ``bid`` in ``u`` or record why not. Overrides raise instead of dropping."""
    w, ts = ctx.world, ctx.ts
    b = w.buildings[bid]
    res = w.res[u.key]

    def fail(msg: str, tech: bool = False) -> None:
        if override:
            raise BuildingHistoryError(f"override {u.key} / c:{u.tag}: {bid}: {msg}")
        u.dropped.append((bid, msg))

    if levels <= 0:
        return
    if not b.buildable or b.ownership_type == "other":
        return fail("not a buildable building")
    r = building_gate(b, ts)
    if r:
        return fail(f"tech gate: {r}" + (f" (tag {u.tag}; state {u.key})" if override else ""))
    if b.city_type == "port" and not res.port:
        return fail("state has no port hub")
    is_arable = b.file in ARABLE_FILES
    if b.file in RESOURCE_FILES:
        if is_arable:
            if bid not in res.arable:
                return fail("state resources lack this arable building")
            levels = min(levels, arable_left["n"]) if not override else levels
            if levels > arable_left["n"]:
                return fail(f"{levels} levels exceed the {arable_left['n']} arable levels left")
        else:
            cap = dict(res.capped).get(bid)
            if cap is None:
                return fail("state resources lack this capped building")
            left = cap - capped_left.get(bid, 0)
            if levels > left:
                if override:
                    return fail(f"{levels} levels exceed the cap {cap}")
                levels = left
    if levels <= 0:
        return fail("no resource capacity left")
    pms, why_not = choose_pms(b, w.groups, w.pms, ts)
    if pms is None:
        return fail(f"tech gate: {why_not}" + (f" (tag {u.tag}; state {u.key})" if override else ""))
    jpl = sum(w.pms[m].jobs for m in pms)
    if jpl > 0:
        fit = remaining[0] // jpl
        if levels > fit:
            if override:
                return fail(f"{levels} levels need {levels * jpl} jobs but only {remaining[0]} fit the workforce share")
            levels = fit
        if levels <= 0:
            return fail("workforce share exhausted (rest stays on subsistence)")
    private = _ownership_mode(b, ts.laws, ts.resolved)
    if private is not None:
        ob = w.buildings.get(private)
        og = building_gate(ob, ts) if ob else "missing"
        opm, _ = choose_pms(ob, w.groups, w.pms, ts) if ob and not og else (None, "")
        if ob is None or og or opm is None:
            u.dropped.append((bid, f"private ownership via {private} not placeable; placed country-owned"))
            private = None
    remaining[0] -= levels * jpl
    u.jobs += levels * jpl
    if is_arable:
        arable_left["n"] -= levels
    elif b.file in RESOURCE_FILES:
        capped_left[bid] = capped_left.get(bid, 0) + levels
    u.placed.append(Placed(bid, levels, pms, private, why))
    if private:
        u.owner_levels[private] = u.owner_levels.get(private, 0) + levels


def _plan_tag(tag, units, ts, prof, cfg, world) -> None:
    ctx = _Ctx(tag, ts, world, cfg)
    state: dict[str, dict] = {}
    for u in units:
        r = world.res[u.key]
        state[u.key] = {"rem": [int(prof["workforce_share"] * u.pop)], "ar": {"n": r.arable_land}, "cap": {}}

    def put(u, bid, levels, override=False, why=""):
        s = state[u.key]
        _try_place(u, bid, levels, ctx, s["rem"], s["ar"], s["cap"], override, why)

    by_key = {u.key: u for u in units}
    # 1. overrides first: they are the canon specifics and are errors when impossible.
    for o in cfg.overrides:
        if o["key"] not in by_key:
            continue
        if o.get("owner") and o["owner"] != tag:
            continue
        u = by_key[o["key"]]
        for bid, lv in o["buildings"].items():
            put(u, bid, int(lv), True, f"override ({o['source']})")
    taken = {(u.key, p.building) for u in units for p in u.placed}

    def auto(u, bid, levels, why):
        if (u.key, bid) in taken:
            return
        put(u, bid, levels, False, why)

    if units:
        if prof["admin"]:
            auto(units[0], "building_government_administration", prof["admin"], "profile admin")
        n = max(prof["barracks_states"], 0)
        for u, lv in zip(units[:n], _split(prof["barracks_levels"], n)):
            auto(u, "building_barrack", lv, "profile barracks")
        if prof["construction"]:
            auto(units[0], "building_construction_sector", prof["construction"], "profile construction")
        ports = [u for u in units if world.res[u.key].port]
        if prof["port_level"]:
            for u in ports[:prof["port_states"]]:
                auto(u, "building_port", prof["port_level"], "profile port")
        if prof["trade_level"]:
            order = ports + [u for u in units if not world.res[u.key].port]
            for u in order[:prof["trade_states"]]:
                auto(u, "building_trade_center", prof["trade_level"], "profile trade")
        for u in units:
            r = world.res[u.key]
            n_ar = int(prof["farm_share"] * r.arable_land + 0.5)
            if r.arable:
                for i, bid in enumerate(r.arable):
                    lv = n_ar // len(r.arable) + (1 if i < n_ar % len(r.arable) else 0)
                    auto(u, bid, lv, "profile farms")
            for bid, cap in r.capped:
                if bid == "building_logging_camp":
                    auto(u, bid, int(prof["logging_share"] * cap + 0.5), "profile logging")
    # the game creates the owner buildings (manor house / financial district) from add_ownership; their
    # employment still counts against the job share, so add it here without emitting them
    for u in units:
        for ob, lv in sorted(u.owner_levels.items()):
            pms, _ = choose_pms(world.buildings[ob], world.groups, world.pms, ts)
            assert pms is not None
            u.jobs += lv * sum(world.pms[m].jobs for m in pms)
        if u.pop and u.jobs > JOB_SHARE_CAP * u.pop:
            raise BuildingHistoryError(f"{u.key} / c:{u.tag}: {u.jobs} jobs exceed {JOB_SHARE_CAP:.0%} of {u.pop} pops")


