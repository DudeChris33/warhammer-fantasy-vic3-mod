def render_file(units: list[Unit]) -> str:
    units = [u for u in units if u.placed]
    if not units:
        return HEADER
    L = [HEADER.rstrip("\n"), "BUILDINGS = {"]
    cur = None
    for u in units:
        if u.key != cur:
            if cur is not None:
                L.append("\t}")
            L.append(f"\ts:{u.key} = {{")
            cur = u.key
        L.append(f"\t\tregion_state:{u.tag} = {{")
        for p in u.placed:
            L.append("\t\t\tcreate_building = {")
            L.append(f'\t\t\t\tbuilding = "{p.building}"')
            if p.private:
                L.append("\t\t\t\tadd_ownership = {")
                L.append("\t\t\t\t\tbuilding = {")
                L.append(f'\t\t\t\t\t\ttype = "{p.private}"')
                L.append(f'\t\t\t\t\t\tcountry = "c:{u.tag}"')
                L.append(f"\t\t\t\t\t\tlevels = {p.levels}")
                L.append(f'\t\t\t\t\t\tregion = "{u.key}"')
                L.append("\t\t\t\t\t}")
                L.append("\t\t\t\t}")
            else:
                L.append("\t\t\t\tadd_ownership = {")
                L.append("\t\t\t\t\tcountry = {")
                L.append(f'\t\t\t\t\t\tcountry = "c:{u.tag}"')
                L.append(f"\t\t\t\t\t\tlevels = {p.levels}")
                L.append("\t\t\t\t\t}")
                L.append("\t\t\t\t}")
            L.append("\t\t\t\treserves = 1")
            L.append("\t\t\t\tactivate_production_methods = { " + " ".join(f'"{m}"' for m in p.pms) + " }")
            L.append("\t\t\t}")
        L.append("\t\t}")
    L.append("\t}")
    L.append("}")
    return "\n".join(L) + "\n"


def render_all(p: Plan) -> dict[str, str]:
    return {f: render_file(us) for f, us in p.files.items()}


