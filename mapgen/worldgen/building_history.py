"""Starting buildings as game script: ``common/history/buildings/NN_*.txt``.

Turns the hand-authored ``mapgen/config/building_history/`` (see its README) into the
vanilla history shape::

    BUILDINGS = {
    	s:STATE_X = {
    		region_state:TAG = {
    			create_building = {
    				building = "building_wheat_farm"
    				add_ownership = { building = { type = "building_manor_house" country = "c:TAG" levels = 5 region = "STATE_X" } }
    				reserves = 1
    				activate_production_methods = { "pm_simple_farming" ... }
    			}
    		}
    	}
    }

THE TECH GATE (the rule this module exists to enforce)
-------------------------------------------------------
A building or production method placed in a country that has not researched its
unlocking technology crashes the game at load. So nothing is emitted unless the owner's
starting tech and laws allow it, and every failure goes *closed*:

* A tag's techs and laws come ONLY from what the files in ``common/history/countries/``
  runs for it: ``add_technology_researched`` lines and nested scripted effects
  (``common/scripted_effects``), ``activate_law`` (last law of a group wins) and
  ``if``/``else`` on ``is_country_type``. Any construct it cannot evaluate, a missing tag
  block or a duplicated block makes the tag **unresolved**: it then has no techs and no
  laws (so only tech-free buildings and law-free methods can be placed).
* A building needs **every** tech in its ``unlocking_technologies``, and is skipped
  outright if it has a ``possible`` trigger (not provable statically).
* One production method per group of the building. A method needs every tech in
  ``unlocking_technologies``, every law in ``unlocking_laws``, none of
  ``disallowing_laws`` (a tag with unresolved laws fails any method that has either law
  list), every method in ``unlocking_production_methods`` among those already chosen for
  the building, and none of ``unlocking_principles`` / ``unlocking_identity`` /
  ``unlocking_company_categories`` / ``unlocking_geographic_regions``. The ``is_default``
  method is preferred, else the first permitted one; a group with no permitted method drops
  the building (reported).
* A hand-authored override asking for a building or method the owner has not unlocked is a
  :class:`BuildingHistoryError` naming tag, state, building / method and the missing tech.
* ``validate_building_history.py`` re-checks the *emitted* files with separate code.

Pure and deterministic: no clock, no filesystem beyond the paths handed in.
"""

