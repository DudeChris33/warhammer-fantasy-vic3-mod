class BuildingHistoryError(Exception):
    """A hard error: bad id, bad override, tech-gate violation, resource or job-limit breach."""


# ---------------------------------------------------------------------------
# Clausewitz parsing (small, tolerant; shares nothing with the verifier)
# ---------------------------------------------------------------------------

_TOK = re.compile(r'"[^"]*"|[{}]|[=<>!?]+|[^\s{}=<>!?"]+')


def parse(text: str) -> list[tuple[str | None, str | None, object]]:
    """``[(key, op, value)]``; value is a string or a nested list; bare tokens have key None."""
    toks = _TOK.findall(re.sub(r"#[^\n]*", "", text.lstrip("﻿")))
    pos = 0

    def block() -> list:
        nonlocal pos
        out: list = []
        while pos < len(toks):
            t = toks[pos]
            if t == "}":
                pos += 1
                return out
            if pos + 2 < len(toks) and toks[pos + 1] in ("=", "?=", ">=", "<=", ">", "<", "!="):
                op = toks[pos + 1]
                if toks[pos + 2] == "{":
                    pos += 3
                    out.append((t.strip('"'), op, block()))
                else:
                    out.append((t.strip('"'), op, toks[pos + 2].strip('"')))
                    pos += 3
            else:
                out.append((None, None, t.strip('"')))
                pos += 1
        return out

    return block()


def _get(items, key):
    for k, _, v in items:
        if k == key:
            return v
    return None


def _bare(items) -> list[str]:
    return [v for k, _, v in items if k is None and isinstance(v, str)]


def _list_field(items, key) -> list[str]:
    v = _get(items, key)
    return _bare(v) if isinstance(v, list) else []


