def _tech_rank(world: World, techs) -> tuple[int, str]:
    best = (-1, "")
    for t in techs:
        best = max(best, (world.eras.get(t, 0), t))
    return best


def markdown_report(cfg: Config, world: World, p: Plan) -> str:
    L: list[str] = []
    by_tag: dict[str, list[Unit]] = {}
    for u in p.units:
        by_tag.setdefault(u.tag, []).append(u)
    L += ["## Tech gate: most advanced building and production method per tag\n",
          "Techs come only from the `common/history/countries/` files; `none` = no technology needed. Ranked by the era of the "
          "unlocking tech, then name. *Techs relied on* is every distinct tech any emitted building or method of the tag needs.\n",
          "| Tag | Resolved | Most advanced building | Unlocked by | Most advanced method | Unlocked by | Techs relied on |",
          "|---|---|---|---|---|---|---|"]
    for tag in sorted(by_tag):
        ts = world.tags.get(tag)
        bb, bm = ("none", (-1, "")), ("none", (-1, ""))
        bt, mt = "none", "none"
        used: set[str] = set()
        for u in by_tag[tag]:
            for x in u.placed:
                b = world.buildings[x.building]
                used |= set(b.techs)
                rk = _tech_rank(world, b.techs)
                if bb[0] == "none" or rk > bb[1]:
                    bb, bt = (x.building, rk), ", ".join(b.techs) or "none"
                for m in x.pms:
                    used |= set(world.pms[m].techs)
                    mrk = _tech_rank(world, world.pms[m].techs)
                    if bm[0] == "none" or mrk > bm[1]:
                        bm, mt = (m, mrk), ", ".join(world.pms[m].techs) or "none"
        L.append(f"| {tag} | {'yes' if ts and ts.resolved else 'NO'} | {bb[0]} | {bt} | {bm[0]} | {mt} | {', '.join(sorted(used)) or 'none'} |")
    cats = sorted({c for c in CATEGORY_BY_FILE.values()})
    L += ["", "## Jobs vs. pops, and buildings emitted per tag by category (levels)\n",
          f"Hard cap: total jobs in a (state, owner) may not exceed {JOB_SHARE_CAP:.0%} of its pops; each archetype "
          f"sets its own `workforce_share` at or below that. The rest of the pops stay on subsistence.\n",
          "| Tag | Pops | Jobs share | Highest state share | Levels by category |", "|---|---|---|---|---|"]
    for tag in sorted(by_tag):
        us = by_tag[tag]
        pop, jobs = sum(u.pop for u in us), sum(u.jobs for u in us)
        hi = max((u.jobs / u.pop if u.pop else 0) for u in us)
        row = {c: 0 for c in cats}
        for u in us:
            for x in u.placed:
                row[world.buildings[x.building].category] += x.levels
        cs = ", ".join(f"{c} {n}" for c, n in row.items() if n) or "none"
        L.append(f"| {tag} | {pop:,} | {jobs / pop:.1%} | {hi:.1%} | {cs} |" if pop else f"| {tag} | 0 | - | - | {cs} |")
    L += ["", "## Overrides\n", "| State | Owner | Buildings | Source | Why |", "|---|---|---|---|---|"]
    for o in cfg.overrides:
        L.append(f"| {o['key']} | {o.get('owner', 'all')} | {', '.join(f'{b} x{v}' for b, v in o['buildings'].items())} | {o['source']} | {o['why']} |")
    L += ["", "## Blocked by resources (not emitted)\n", "| State | Building | Source | Why |", "|---|---|---|---|"]
    for o in cfg.blocked_res:
        L.append(f"| {o['key']} | {o['building']} | {o['source']} | {o['why']} |")
    L += ["", "## Blocked by technology (not emitted)\n", "| State | Tag | Building | Needs | Source | Why |", "|---|---|---|---|---|---|"]
    for o in cfg.blocked_tech:
        need = ", ".join(world.buildings[o["building"]].techs) or "(a production method)"
        L.append(f"| {o['key']} | {o['tag']} | {o['building']} | {o.get('needs', need)} | {o['source']} | {o['why']} |")
    L += ["", "## Warhammer concepts with no fitting building (gaps)\n"]
    L += [f"- **{g['concept']}**: {g['why']}" for g in cfg.gaps] or ["- none"]
    L += ["", "## Dropped or skipped\n"]
    agg: dict[str, dict[str, dict[str, int]]] = {}
    for u in p.units:
        for b, why in u.dropped:
            kind = ("tech gate" if why.startswith("tech gate") else "workforce share" if why.startswith("workforce")
                    else "resource" if "resource" in why or "capacity" in why else "other")
            if kind == "tech gate":
                need = why.split(" needs ")[-1] if " needs " in why else why
                b = f"{b} [{need}]"
            elif kind == "other":
                b = f"{b} ({why})"
            d = agg.setdefault(u.tag, {}).setdefault(kind, {})
            d[b] = d.get(b, 0) + 1
    for t in sorted(agg):
        parts = [f"{k}: " + ", ".join(f"{b} x{n}" for b, n in sorted(v.items())) for k, v in sorted(agg[t].items())]
        L.append(f"- **{t}** -- " + "; ".join(parts))
    if not agg:
        L.append("- none")
    L += ["", "**Warnings:**", ""] + ([f"- {w}" for w in p.warnings] or ["- none"])
    return "\n".join(L) + "\n"


def summary(p: Plan, world: World) -> str:
    n = sum(len(u.placed) for u in p.units)
    dropped = sum(len(u.dropped) for u in p.units)
    unresolved = sorted(t for t in {u.tag for u in p.units} if not (world.tags.get(t) and world.tags[t].resolved))
    s = f"{n} buildings in {sum(1 for u in p.units if u.placed)} region_states, {dropped} drops"
    if unresolved:
        s += f"; UNRESOLVED tech sets (tech-free only): {', '.join(unresolved)}"
    return s
