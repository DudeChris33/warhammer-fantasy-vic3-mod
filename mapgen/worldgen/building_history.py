@dataclass(frozen=True)
class Building:
    id: str
    techs: tuple[str, ...]
    groups: tuple[str, ...]
    has_possible: bool
    ownership_type: str      # self | other | (blank: country only)
    buildable: bool
    city_type: str
    file: str

    @property
    def category(self) -> str:
        return CATEGORY_BY_FILE.get(self.file, "other")


@dataclass(frozen=True)
class Pm:
    id: str
    techs: tuple[str, ...]
    laws_in: tuple[str, ...]
    laws_out: tuple[str, ...]
    pms_in: tuple[str, ...]
    forbidden: tuple[str, ...]
    is_default: bool
    jobs: int


def load_buildings(d: Path) -> dict[str, Building]:
    out: dict[str, Building] = {}
    for p in sorted(Path(d).glob("*.txt")):
        for k, _, v in parse(p.read_text(encoding="utf-8-sig")):
            if not isinstance(v, list):
                continue
            own = _get(v, "ownership_type")
            bld = _get(v, "buildable")
            out[k] = Building(k, tuple(_list_field(v, "unlocking_technologies")),
                              tuple(_list_field(v, "production_method_groups")),
                              _get(v, "possible") is not None,
                              own if isinstance(own, str) else "",
                              bld != "no", _get(v, "city_type") or "", p.name)
    return out


def load_groups(d: Path) -> dict[str, list[str]]:
    out: dict[str, list[str]] = {}
    for p in sorted(Path(d).glob("*.txt")):
        for k, _, v in parse(p.read_text(encoding="utf-8-sig")):
            if isinstance(v, list):
                out[k] = _list_field(v, "production_methods")
    return out


def _jobs(v) -> int:
    bm = _get(v, "building_modifiers")
    if not isinstance(bm, list):
        return 0
    ls = _get(bm, "level_scaled")
    if not isinstance(ls, list):
        return 0
    total = 0
    for k, _, x in ls:
        if k and k.startswith("building_employment_") and k.endswith("_add") and isinstance(x, str):
            total += int(float(x))
    return total


def load_pms(d: Path) -> dict[str, Pm]:
    out: dict[str, Pm] = {}
    for p in sorted(Path(d).glob("*.txt")):
        for k, _, v in parse(p.read_text(encoding="utf-8-sig")):
            if not isinstance(v, list):
                continue
            forb = tuple(f for f in FORBIDDEN_PM_FIELDS if _get(v, f) is not None)
            out[k] = Pm(k, tuple(_list_field(v, "unlocking_technologies")), tuple(_list_field(v, "unlocking_laws")),
                        tuple(_list_field(v, "disallowing_laws")), tuple(_list_field(v, "unlocking_production_methods")),
                        forb, _get(v, "is_default") == "yes", _jobs(v))
    return out


def load_law_groups(d: Path) -> dict[str, str]:
    out: dict[str, str] = {}
    for p in sorted(Path(d).glob("*.txt")):
        for k, _, v in parse(p.read_text(encoding="utf-8-sig")):
            if isinstance(v, list):
                g = _get(v, "group")
                out[k] = g if isinstance(g, str) else k
    return out


def load_tech_eras(d: Path) -> dict[str, int]:
    out: dict[str, int] = {}
    for p in sorted(Path(d).glob("*.txt")):
        for k, _, v in parse(p.read_text(encoding="utf-8-sig")):
            if isinstance(v, list):
                e = _get(v, "era")
                if isinstance(e, str) and e.startswith("era_"):
                    out[k] = int(e[4:])
    return out


def load_country_types(d: Path) -> dict[str, str | None]:
    """``{tag: country_type}`` of the non-dynamic tags."""
    out: dict[str, str | None] = {}
    for p in sorted(Path(d).glob("*.txt")):
        for k, _, v in parse(p.read_text(encoding="utf-8-sig")):
            if isinstance(v, list) and re.fullmatch(r"[A-Z][A-Z0-9]{2}", k) and _get(v, "dynamic_country_definition") != "yes":
                t = _get(v, "country_type")
                out[k] = t if isinstance(t, str) else None
    return out


# ---------------------------------------------------------------------------
# The tech gate: what a tag has researched / which laws it runs
# ---------------------------------------------------------------------------

class _Unresolved(Exception):
    pass


def load_effect_defs(d: Path) -> dict[str, list]:
    out: dict[str, list] = {}
    for p in sorted(Path(d).glob("*.txt")):
        for k, _, v in parse(p.read_text(encoding="utf-8-sig")):
            if isinstance(v, list):
                out[k] = v
    return out


def _run_effects(items, ctype, techs: set, laws: dict, defs, law_groups, stack: tuple) -> None:
    last_if: bool | None = None       # result of the immediately preceding ``if`` (for its ``else``)
    for k, op, v in items:
        prev, last_if = last_if, None
        if k == "add_technology_researched" and isinstance(v, str):
            techs.add(v)
        elif k == "add_era_researched":
            pass
        elif k == "activate_law" and isinstance(v, str) and v.startswith("law_type:"):
            law = v[len("law_type:"):]
            laws[law_groups.get(law, law)] = law
        elif k == "if" and isinstance(v, list):
            lim = _get(v, "limit")
            if not (isinstance(lim, list) and len(lim) == 1 and lim[0][0] == "is_country_type"
                    and isinstance(lim[0][2], str)):
                raise _Unresolved("unevaluable if-limit")
            last_if = ctype == lim[0][2]
            if last_if:
                _run_effects([i for i in v if i[0] != "limit"], ctype, techs, laws, defs, law_groups, stack)
        elif k == "else" and isinstance(v, list):
            if prev is None:
                raise _Unresolved("else without if")
            if not prev:
                _run_effects(v, ctype, techs, laws, defs, law_groups, stack)
        elif isinstance(v, str) and v == "yes" and k in defs:
            if k in stack:
                raise _Unresolved("effect cycle")
            _run_effects(defs[k], ctype, techs, laws, defs, law_groups, stack + (k,))
        else:
            raise _Unresolved(f"cannot evaluate {k!r}")


@dataclass(frozen=True)
class TagState:
    techs: frozenset[str]
    laws: frozenset[str]
    resolved: bool
    why: str = ""


def resolve_tags(setup_text: str | None, defs, law_groups, ctypes) -> dict[str, TagState]:
    """``{tag: TagState}`` for every tag the start setup mentions. An unresolvable or duplicated
    block gives an empty, ``resolved=False`` state."""
    out: dict[str, TagState] = {}
    if not setup_text:
        return out
    blocks = [(m.group(1), m.start()) for m in re.finditer(r"\bc:(\w+)\s*\?=\s*\{", re.sub(r"#[^\n]*", "", setup_text))]
    seen: dict[str, int] = {}
    for tag, _ in blocks:
        seen[tag] = seen.get(tag, 0) + 1
    items = parse(setup_text)
    root = [e for k, _, v in items if k == "COUNTRIES" and isinstance(v, list) for e in v]
    for k, _, v in root:
        if not (k and k.startswith("c:") and isinstance(v, list)):
            continue
        tag = k[2:]
        if seen.get(tag, 0) != 1:
            out[tag] = TagState(frozenset(), frozenset(), False, "tag appears more than once")
            continue
        if tag not in ctypes:
            out[tag] = TagState(frozenset(), frozenset(), False, "no country definition")
            continue
        techs: set[str] = set()
        laws: dict[str, str] = {}
        try:
            _run_effects(v, ctypes[tag], techs, laws, defs, law_groups, ())
        except _Unresolved as exc:
            out[tag] = TagState(frozenset(), frozenset(), False, str(exc))
            continue
        out[tag] = TagState(frozenset(techs), frozenset(laws.values()), True)
    return out


def pm_gate(pm: Pm, ts: TagState, chosen: set[str]) -> str | None:
    """None when ``pm`` may be placed for this tag, else why not."""
    if pm.forbidden:
        return f"{pm.id} needs {pm.forbidden[0]}"
    miss = [t for t in pm.techs if t not in ts.techs]
    if miss:
        return f"{pm.id} needs tech {miss[0]}"
    if pm.laws_in or pm.laws_out:
        if not ts.resolved:
            return f"{pm.id} has a law condition and the tag's laws are unresolved"
        miss = [l for l in pm.laws_in if l not in ts.laws]
        if miss:
            return f"{pm.id} needs law {miss[0]}"
        bad = [l for l in pm.laws_out if l in ts.laws]
        if bad:
            return f"{pm.id} is disallowed by law {bad[0]}"
    miss = [p for p in pm.pms_in if p not in chosen]
    if miss:
        return f"{pm.id} needs method {miss[0]}"
    return None


def building_gate(b: Building, ts: TagState) -> str | None:
    if b.has_possible:
        return f"{b.id} has a possible trigger"
    miss = [t for t in b.techs if t not in ts.techs]
    if miss:
        return f"{b.id} needs tech {miss[0]}"
    return None


def choose_pms(b: Building, groups, pms, ts: TagState) -> tuple[list[str] | None, str]:
    """One permitted method per group, default first, else first permitted; ``(None, why)`` when a group has none."""
    chosen: list[str] = []
    for g in b.groups:
        if g not in groups:
            raise BuildingHistoryError(f"{b.id}: production method group {g} is not defined")
        cands = [m for m in groups[g]]
        for m in cands:
            if m not in pms:
                raise BuildingHistoryError(f"{g}: production method {m} is not defined")
        ordered = [m for m in cands if pms[m].is_default] + [m for m in cands if not pms[m].is_default]
        pick, why = None, ""
        for m in ordered:
            r = pm_gate(pms[m], ts, set(chosen))
            if r is None:
                pick = m
                break
            if not why:
                why = r
        if pick is None:
            return None, f"group {g}: no permitted method ({why})"
        chosen.append(pick)
    return chosen, ""


