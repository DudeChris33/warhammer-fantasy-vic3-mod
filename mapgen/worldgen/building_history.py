def parse_emitted(text: str) -> list[tuple[str, str, list[dict]]]:
    """``[(state, tag, [{building, levels, pms, owner_type, owner_levels}])]`` of one emitted file."""
    out = []
    root = next((v for k, _, v in parse(text) if k == "BUILDINGS" and isinstance(v, list)), [])
    for sk, _, sv in root:
        if not (sk and sk.startswith("s:") and isinstance(sv, list)):
            raise BuildingHistoryError(f"unexpected top-level entry {sk!r}")
        for rk, _, rv in sv:
            if not (rk and rk.startswith("region_state:") and isinstance(rv, list)):
                raise BuildingHistoryError(f"{sk}: unexpected entry {rk!r}")
            bl = []
            for ck, _, cv in rv:
                if ck != "create_building" or not isinstance(cv, list):
                    raise BuildingHistoryError(f"{sk}: unexpected entry {ck!r}")
                own = _get(cv, "add_ownership")
                lv, ot = None, None
                if isinstance(own, list):
                    inner = own[0][2] if own else []
                    ot = _get(inner, "type") if isinstance(inner, list) else None
                    lvs = _get(inner, "levels") if isinstance(inner, list) else None
                    lv = int(lvs) if isinstance(lvs, str) else None
                else:
                    lvs = _get(cv, "level")
                    lv = int(lvs) if isinstance(lvs, str) else None
                bl.append({"building": _get(cv, "building"), "levels": lv, "owner_type": ot,
                           "pms": _bare(_get(cv, "activate_production_methods") or [])})
            out.append((sk[2:], rk[len("region_state:"):], bl))
    return out


def invariants(p: Plan, cfg: Config, world: World) -> list[str]:
    errs: list[str] = []
    for u in p.units:
        r = world.res[u.key]
        arable = sum(x.levels for x in u.placed if world.buildings[x.building].file in ARABLE_FILES)
        if arable > r.arable_land:
            errs.append(f"{u.key}/{u.tag}: {arable} arable levels exceed arable_land {r.arable_land}")
        for x in u.placed:
            b = world.buildings[x.building]
            if b.file in ARABLE_FILES and x.building not in r.arable:
                errs.append(f"{u.key}/{u.tag}: {x.building} is not an arable resource of the state")
            if b.file in RESOURCE_FILES and b.file not in ARABLE_FILES:
                cap = dict(r.capped).get(x.building)
                if cap is None or x.levels > cap:
                    errs.append(f"{u.key}/{u.tag}: {x.building} {x.levels} exceeds the capped resource {cap}")
            if b.city_type == "port" and not r.port:
                errs.append(f"{u.key}/{u.tag}: {x.building} in a state with no port hub")
        if u.pop and u.jobs > JOB_SHARE_CAP * u.pop:
            errs.append(f"{u.key}/{u.tag}: jobs {u.jobs} exceed {JOB_SHARE_CAP:.0%} of pops {u.pop}")
        if u.tag == UNO:
            errs.append(f"{u.key}: buildings for c:UNO")
    return errs


def check_texts(texts: dict[str, str], world: World) -> list[str]:
    """Ids and brace balance of the emitted text, plus (state, owner) pairs that history/states creates."""
    errs: list[str] = []
    for name, text in sorted(texts.items()):
        if text.count("{") != text.count("}"):
            errs.append(f"{name}: braces do not balance")
            continue
        try:
            rows = parse_emitted(text)
        except BuildingHistoryError as exc:
            errs.append(f"{name}: {exc}")
            continue
        for st, tag, bl in rows:
            if tag not in world.owners.get(st, []):
                errs.append(f"{name}: {st}/c:{tag} is not a (state, owner) pair history/states creates")
            for x in bl:
                if x["building"] not in world.buildings:
                    errs.append(f"{name}: unknown building {x['building']}")
                for m in x["pms"]:
                    if m not in world.pms:
                        errs.append(f"{name}: unknown production method {m}")
    return errs


