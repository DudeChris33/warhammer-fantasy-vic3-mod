@dataclass(frozen=True)
class StateRes:
    key: str
    arable_land: int
    arable: tuple[str, ...]
    capped: tuple[tuple[str, int], ...]
    port: bool


@dataclass
class World:
    files: dict[str, list[str]]                 # region file -> state keys (file order)
    res: dict[str, StateRes]
    anchors: dict[str, list[int]]
    owners: dict[str, list[str]]                # state -> owner tags (non-UNO, sorted)
    pops: dict[tuple[str, str], int]
    buildings: dict[str, Building]
    groups: dict[str, list[str]]
    pms: dict[str, Pm]
    tags: dict[str, TagState]
    eras: dict[str, int]
    known_tags: set[str]


def parse_state_resources(text: str) -> dict[str, StateRes]:
    out: dict[str, StateRes] = {}
    for k, _, v in parse(text):
        if not (k and k.startswith("STATE_") and isinstance(v, list)):
            continue
        al = _get(v, "arable_land")
        cap = _get(v, "capped_resources")
        capped = tuple((a, int(c)) for a, _, c in cap if a and isinstance(c, str)) if isinstance(cap, list) else ()
        out[k] = StateRes(k, int(al) if isinstance(al, str) else 0, tuple(_list_field(v, "arable_resources")),
                          capped, _get(v, "port") is not None)
    return out


def parse_pops(text: str) -> dict[tuple[str, str], int]:
    out: dict[tuple[str, str], int] = {}
    root = next((v for k, _, v in parse(text) if k == "POPS" and isinstance(v, list)), [])
    for sk, _, sv in root:
        if not (sk and sk.startswith("s:") and isinstance(sv, list)):
            continue
        for rk, _, rv in sv:
            if rk and rk.startswith("region_state:") and isinstance(rv, list):
                tot = 0
                for ck, _, cv in rv:
                    if ck == "create_pop" and isinstance(cv, list):
                        s = _get(cv, "size")
                        tot += int(s) if isinstance(s, str) else 0
                out[(sk[2:], rk[len("region_state:"):])] = out.get((sk[2:], rk[len("region_state:"):]), 0) + tot
    return out


def load_world(root: Path) -> World:
    sr = root / "map_data" / "state_regions"
    files: dict[str, list[str]] = {}
    res: dict[str, StateRes] = {}
    for p in sorted(sr.glob("*.txt")):
        if p.name.startswith("99_"):
            continue
        text = p.read_text(encoding="utf-8-sig")
        r = parse_state_resources(text)
        files[p.name] = list(r)
        res.update(r)
    own = json.loads((root / "mapgen" / "derived" / "state_ownership.json").read_text(encoding="utf-8"))
    anchors = {k: v.get("naming_anchor") for k, v in own["states"].items()}
    owners: dict[str, list[str]] = {}
    for p in sorted((root / "common" / "history" / "states").glob("*.txt")):
        for key, creates in sh.parse_history_text(p.read_text(encoding="utf-8-sig")):
            tags = sorted({t for t, _ in creates if t and t != UNO})
            if tags:
                owners[key] = tags
    pops: dict[tuple[str, str], int] = {}
    for p in sorted((root / "common" / "history" / "pops").glob("*.txt")):
        pops.update(parse_pops(p.read_text(encoding="utf-8-sig")))
    c = root / "common"
    setup = sorted((c / "history" / "countries").glob("*.txt"))
    law_groups = load_law_groups(c / "laws")
    tags = resolve_tags("\n".join(f.read_text(encoding="utf-8-sig") for f in setup),
                        load_effect_defs(c / "scripted_effects"), law_groups, load_country_types(c / "country_definitions"))
    return World(files, res, anchors, owners, pops, load_buildings(c / "buildings"),
                 load_groups(c / "production_method_groups"), load_pms(c / "production_methods"), tags,
                 load_tech_eras(c / "technology" / "technologies"), set(load_country_types(c / "country_definitions")))


@dataclass
class Config:
    job_cap: float
    archetypes: dict[str, dict]
    tags: dict[str, dict]
    overrides: list[dict]
    blocked_res: list[dict]
    blocked_tech: list[dict]
    gaps: list[dict]


def _need(d: dict, keys, where: str) -> None:
    for k in keys:
        if k not in d or d[k] in ("", None):
            raise BuildingHistoryError(f"{where}: missing {k!r}")


ARCH_FIELDS = ("admin", "barracks_levels", "barracks_states", "construction", "port_level", "port_states",
               "trade_level", "trade_states", "farm_share", "logging_share", "workforce_share")


def load_config(d: Path) -> Config:
    prof = json.loads((d / "profiles.json").read_text(encoding="utf-8"))
    ov = json.loads((d / "state_overrides.json").read_text(encoding="utf-8"))
    bl = json.loads((d / "blocked.json").read_text(encoding="utf-8"))
    cap = float(prof.get("job_share_cap", JOB_SHARE_CAP))
    if cap > JOB_SHARE_CAP:
        raise BuildingHistoryError(f"profiles.json: job_share_cap {cap} exceeds the hard cap {JOB_SHARE_CAP}")
    for n, a in prof["archetypes"].items():
        _need(a, ARCH_FIELDS + ("source", "why"), f"profiles.json archetype {n}")
        if a["workforce_share"] > cap:
            raise BuildingHistoryError(f"profiles.json archetype {n}: workforce_share {a['workforce_share']} exceeds job_share_cap {cap}")
    for t, e in prof["tags"].items():
        _need(e, ("archetype",), f"profiles.json tag {t}")
        if e["archetype"] not in prof["archetypes"]:
            raise BuildingHistoryError(f"profiles.json tag {t}: unknown archetype {e['archetype']!r}")
        for f, val in e.get("set", {}).items():
            if f not in ARCH_FIELDS:
                raise BuildingHistoryError(f"profiles.json tag {t}: unknown field {f!r}")
            if f not in e.get("justify", {}) or not {"source", "why"} <= set(e["justify"][f]):
                raise BuildingHistoryError(f"profiles.json tag {t}: field {f!r} override needs a justify entry with source and why")
    for n, o in enumerate(ov["states"]):
        _need(o, ("key", "anchor", "buildings", "source", "why"), f"state_overrides.json state {n}")
    for n, o in enumerate(bl["blocked_by_resources"]):
        _need(o, ("key", "anchor", "building", "source", "why"), f"blocked.json blocked_by_resources {n}")
    for n, o in enumerate(bl["blocked_by_tech"]):
        _need(o, ("key", "anchor", "tag", "building", "source", "why"), f"blocked.json blocked_by_tech {n}")
    return Config(cap, prof["archetypes"], prof["tags"], ov["states"], bl["blocked_by_resources"],
                  bl["blocked_by_tech"], bl.get("gaps", []))


