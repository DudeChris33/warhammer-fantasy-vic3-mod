#: Per-tag exceptions to the culture rule.
TAG_TECH: dict[str, str | None] = {
    "UNO": None,   # Unclaimed Lands: no polity, no technology
}
POLITICS_EFFECT = "effect_starting_politics_traditional"

_CULTURES = re.compile(r"\bcultures\s*=\s*\{([^}]*)\}")
_BLOCK = re.compile(r"\bc:(\w+)\s*\?=\s*\{")
_EFFECT_USE = re.compile(r"\badd_technology_researched\s*=\s*(\w+)|\b(\w+)\s*=\s*yes\b")
_EFFECT_DEF = re.compile(r"^(\w+)\s*=\s*\{", re.M)
ADD_TECH = "add_technology_researched"


@dataclass
class Plan:
    blocks: list[tuple[str, list[str]]]   # (tag, [effect, ...]) sorted by tag
    held_back: list[str] = field(default_factory=list)   # owner tags with no definition


# ---------------------------------------------------------------------------
# Inputs
# ---------------------------------------------------------------------------

def parse_country_cultures(text: str) -> dict[str, tuple[str, ...]]:
    """``{tag: cultures in listed order}`` for the non-dynamic tags one ``country_definitions``
    file defines (same tag rule as ``state_history.parse_country_tags``); a tag with no
    ``cultures`` block maps to ``()``."""
    text = sh._strip_comments(text.lstrip("﻿"))
    out: dict[str, tuple[str, ...]] = {}
    for m in sh._TAG_HEADER.finditer(text):
        open_idx = text.index("{", m.end() - 1)
        body = text[open_idx + 1:sh._match_brace(text, open_idx)]
        if sh._DYNAMIC.search(body):
            continue
        cm = _CULTURES.search(body)
        out[m.group(1)] = tuple(cm.group(1).split()) if cm else ()
    return out


def load_country_cultures(country_definitions_dir: Path) -> dict[str, tuple[str, ...]]:
    out: dict[str, tuple[str, ...]] = {}
    for path in sorted(Path(country_definitions_dir).glob("*.txt")):
        out.update(parse_country_cultures(path.read_text(encoding="utf-8-sig")))
    return out


def tech_effect(tag: str, cultures: tuple[str, ...]) -> str | None:
    """The starting-technology preset for one tag (``None`` = none). Raises
    :class:`OwnershipError` when neither ``TAG_TECH`` nor the first culture maps."""
    if tag in TAG_TECH:
        return TAG_TECH[tag]
    if not cultures:
        raise OwnershipError(f"c:{tag}: country definition lists no culture, so it has no starting-technology "
                             f"preset (add one to the definition or to TAG_TECH)")
    if cultures[0] not in CULTURE_TECH:
        raise OwnershipError(f"c:{tag}: culture {cultures[0]!r} has no starting-technology preset "
                             f"(known: {', '.join(sorted(CULTURE_TECH))})")
    return CULTURE_TECH[cultures[0]]


def load_effect_names(scripted_effects_dir: Path) -> set[str]:
    """Top-level scripted-effect names defined in ``common/scripted_effects/*.txt``."""
    names: set[str] = set()
    for path in sorted(Path(scripted_effects_dir).glob("*.txt")):
        names |= set(_EFFECT_DEF.findall(sh._strip_comments(path.read_text(encoding="utf-8-sig"))))
    return names


def load_tech_extras(path: Path) -> dict[str, list[str]]:
    """``{tag: [tech id, ...]}`` from ``mapgen/config/starting_tech_extras.json``."""
    doc = json.loads(Path(path).read_text(encoding="utf-8"))
    tags = doc.get("tags")
    if not isinstance(tags, dict):
        raise OwnershipError(f"{path}: no 'tags' object")
    return {tag: list(techs) for tag, techs in tags.items()}


def load_tech_ids(technologies_dir: Path) -> set[str]:
    """Technology ids defined in ``common/technology/technologies/*.txt``."""
    ids: set[str] = set()
    for path in sorted(Path(technologies_dir).glob("*.txt")):
        ids |= set(_EFFECT_DEF.findall(sh._strip_comments(path.read_text(encoding="utf-8-sig"))))
    return ids


def owner_tags(ownership_doc: dict) -> set[str]:
    """Every tag that owns a state or a slice of one at the start date. The
    ``unowned`` / ``placeholder`` tokens map to ``UNO`` (``state_history.TOKEN_OWNER``),
    so it is an owner whenever any state or slice carries one."""
    states = ownership_doc.get("states")
    if not isinstance(states, dict):
        raise OwnershipError("state_ownership.json has no 'states' object")
    tokens: set[str] = set()
    for key, rec in states.items():
        if rec.get("scope") == "placeholder":
            tokens.add(PLACEHOLDER)
        elif "owner" in rec:
            tokens.add(rec["owner"])
        elif "owners" in rec:
            tokens |= {sl["owner"] for sl in rec["owners"]}
        else:
            raise OwnershipError(f"{key}: record has neither 'owner' nor 'owners'")
    return {sh.TOKEN_OWNER.get(t, t) for t in tokens}


# ---------------------------------------------------------------------------
# Plan / render
# ---------------------------------------------------------------------------

def plan(ownership_doc: dict, cultures: dict[str, tuple[str, ...]],
         extras: dict[str, list[str]] | None = None) -> Plan:
    """What to emit. Raises :class:`OwnershipError` for a defined owner whose culture
    has no starting-technology preset."""
    blocks: list[tuple[str, list[str]]] = []
    held: list[str] = []
    for tag in sorted(owner_tags(ownership_doc)):
        if tag not in cultures:
            held.append(tag)
            continue
        tech = tech_effect(tag, cultures[tag])
        techs = [f"{ADD_TECH} = {x}" for x in (extras or {}).get(tag, [])]
        blocks.append((tag, ([tech] if tech else []) + techs + [POLITICS_EFFECT]))
    return Plan(blocks=blocks, held_back=held)


_LOC_NAME = re.compile(r'^\s*([A-Z][A-Z0-9]{2}):\d*\s+"([^"]*)"', re.M)
_BAD_FILE_CHARS = re.compile(r'[<>:"/\|?*\x00-\x1f]')


def load_country_names(localization_dir: Path) -> dict[str, str]:
    """``{TAG: display name}`` from the ``TAG:0 "Name"`` lines of the English ``*.yml`` under ``localization/`` (new loc and ``replace/``)."""
    out: dict[str, str] = {}
    for path in sorted(Path(localization_dir).rglob("*.yml")):
        if "english" not in path.parts:
            continue
        for tag, name in _LOC_NAME.findall(path.read_text(encoding="utf-8-sig")):
            out.setdefault(tag, name)
    return out


def file_name(tag: str, names: dict[str, str]) -> str:
    """``dah - dahomey.txt`` for ``DAH`` -- vanilla's file-per-country layout; just
    ``dah.txt`` when the tag has no localized name."""
    name = _BAD_FILE_CHARS.sub("", names.get(tag, "")).strip().lower()
    return f"{tag.lower()} - {name}.txt" if name else f"{tag.lower()}.txt"


def render_file(tag: str, effects: list[str]) -> str:
    """One tag's history file (no BOM, LF)."""
    lines = [HEADER.rstrip("\n"), "COUNTRIES = {", f"\tc:{tag} ?= {{"]
    lines += [f"\t\t{e}" if " = " in e else f"\t\t{e} = yes" for e in effects]
    lines += ["\t}", "}"]
    return "\n".join(lines) + "\n"


def render(blocks: list[tuple[str, list[str]]], names: dict[str, str]) -> dict[str, str]:
    """``{file name: text}`` for every planned block."""
    return {file_name(tag, names): render_file(tag, effects) for tag, effects in blocks}


# ---------------------------------------------------------------------------
# Validate the emitted file
# ---------------------------------------------------------------------------

def parse_history_text(text: str) -> list[tuple[str, list[str]]]:
    """``[(tag, [effect, ...])]`` in file order (duplicates kept). Comments ignored."""
    text = sh._strip_comments(text.lstrip("﻿"))
    out: list[tuple[str, list[str]]] = []
    idx = 0
    while True:
        m = _BLOCK.search(text, idx)
        if not m:
            break
        open_idx = text.index("{", m.end() - 1)
        close_idx = sh._match_brace(text, open_idx)
        out.append((m.group(1), [f"{ADD_TECH} = {tech}" if tech else eff
                                 for tech, eff in _EFFECT_USE.findall(text[open_idx + 1:close_idx])]))
        idx = close_idx + 1
    return out


def check(texts: dict[str, str] | None, ownership_doc: dict, cultures: dict[str, tuple[str, ...]],
          effect_names: set[str], names: dict[str, str],
          extras: dict[str, list[str]] | None = None,
          tech_ids: set[str] | None = None) -> tuple[list[str], list[str]]:
    """Validate the emitted files (``{file name: text}``). Returns ``(errors, held_back)``;
    ``held_back`` lists JSON owners with no definition (the caller decides whether that is
    an error)."""
    try:
        p = plan(ownership_doc, cultures, extras)
    except OwnershipError as exc:
        return [str(exc)], []
    if not texts:
        return ["common/history/countries has no files -- run generate_country_history.py"], p.held_back
    errors: list[str] = []
    seen: dict[str, int] = {}
    for fname, text in sorted(texts.items()):
        try:
            parsed = parse_history_text(text)
        except OwnershipError as exc:
            errors.append(f"history/countries/{fname}: {exc}")
            continue
        for tag, effects in parsed:
            seen[tag] = seen.get(tag, 0) + 1
            if fname != file_name(tag, names) or len(parsed) != 1:
                errors.append(f"c:{tag}: lives in {fname}, expected one block per file in {file_name(tag, names)}")
            if tag not in cultures:
                errors.append(f"c:{tag}: no (non-dynamic) common/country_definitions entry")
            for e in effects:
                if e.startswith(ADD_TECH + " = "):
                    if tech_ids is not None and e.split(" = ", 1)[1] not in tech_ids:
                        errors.append(f"c:{tag}: {e} names no technology in common/technology")
                elif e not in effect_names:
                    errors.append(f"c:{tag}: {e} is not a scripted effect in common/scripted_effects")
    for tag, n in sorted(seen.items()):
        if n > 1:
            errors.append(f"c:{tag}: appears {n} times in the country history")
    expected = {tag for tag, _ in p.blocks}
    for tag in sorted(expected - set(seen)):
        errors.append(f"c:{tag}: owns a state but has no country history block -- regenerate")
    for tag in sorted(set(seen) - expected - {t for t in seen if t not in cultures}):
        errors.append(f"c:{tag}: has a country history block but owns no state -- regenerate")
    if not errors:
        want = render(p.blocks, names)
        for fname, text in sorted(texts.items()):
            if sh.normalize_text(text) != want[fname]:
                errors.append(f"history/countries/{fname} differs from what the generator emits (culture or effect changed) -- regenerate")
    return errors, p.held_back


def load_history_dir(history_dir: Path) -> dict[str, str]:
    """``{file name: text}`` for every ``*.txt`` in the country history folder."""
    d = Path(history_dir)
    return {p.name: p.read_bytes().decode("utf-8") for p in sorted(d.glob("*.txt"))} if d.is_dir() else {}
