"""Starting country setup as game script: ``common/history/countries/00_start_setup.txt``.

Every tag that owns a state at the start date (``mapgen/derived/state_ownership.json``)
needs a starting setup or its laws and technology are empty. This module writes
the smallest setup vanilla itself uses for a minimal country (e.g.
``game/common/history/countries/dah - dahomey.txt``)::

    COUNTRIES = {
    	c:TAG ?= {
    		effect_starting_technology_tier_5_tech = yes
    		effect_starting_politics_traditional = yes
    	}
    }

Both effects are the vanilla scripted effects restored in
``common/scripted_effects/`` (``00_starting_inventions.txt``,
``00_political_setup.txt``).

Rules
-----
* One block per owner tag: every ``owner`` / ``owners[].owner`` tag, plus ``UNO``
  (Unclaimed Lands, #6391) whenever a state or slice is ``unowned`` or an
  out-of-scope ``placeholder`` -- the same token mapping the state history uses
  (``state_history.TOKEN_OWNER``). A tag with no non-dynamic
  ``common/country_definitions`` entry is **held back** (reported, no block),
  like the state history.
* Starting technology comes from the tag's definition ``tier`` (``TECH_TIER``);
  a tier missing from that table is an error, never a default. Every tag gets
  ``effect_starting_politics_traditional``. This is placeholder-grade: it makes
  each country valid, not historically differentiated.
* Ordering is stable (tags sorted), so an ownership repaint does not churn
  unrelated blocks.

Pure and deterministic: no clock, no filesystem beyond the paths handed in.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path

from . import state_history as sh
from .state_ownership import PLACEHOLDER, OwnershipError

HEADER = ("# GENERATED by mapgen/generate_country_history.py from mapgen/derived/state_ownership.json"
          " and the tiers in common/country_definitions - never hand-edit; repaint"
          " mapgen/config/state_ownership.png, re-read it (read_state_ownership.py) and regenerate.\n")

#: Country definition ``tier`` -> vanilla starting-technology effect
#: (``common/scripted_effects/00_starting_inventions.txt``).
TECH_TIER: dict[str, str] = {
    "empire": "effect_starting_technology_tier_5_tech",
    "hegemony": "effect_starting_technology_tier_5_tech",
    "kingdom": "effect_starting_technology_tier_5_tech",
    "grand_principality": "effect_starting_technology_tier_5_tech",
    "principality": "effect_starting_technology_tier_6_tech",
    "city_state": "effect_starting_technology_tier_6_tech",
}
POLITICS_EFFECT = "effect_starting_politics_traditional"

_TIER = re.compile(r"\btier\s*=\s*(\w+)")
_BLOCK = re.compile(r"\bc:(\w+)\s*\?=\s*\{")
_EFFECT_USE = re.compile(r"\b(\w+)\s*=\s*yes\b")
_EFFECT_DEF = re.compile(r"^(\w+)\s*=\s*\{", re.M)


@dataclass
class Plan:
    blocks: list[tuple[str, list[str]]]   # (tag, [effect, ...]) sorted by tag
    held_back: list[str] = field(default_factory=list)   # owner tags with no definition


# ---------------------------------------------------------------------------
# Inputs
# ---------------------------------------------------------------------------

def parse_country_tiers(text: str) -> dict[str, str | None]:
    """``{tag: tier or None}`` for the non-dynamic tags one ``country_definitions``
    file defines (same tag rule as ``state_history.parse_country_tags``)."""
    text = sh._strip_comments(text.lstrip("﻿"))
    out: dict[str, str | None] = {}
    for m in sh._TAG_HEADER.finditer(text):
        open_idx = text.index("{", m.end() - 1)
        body = text[open_idx + 1:sh._match_brace(text, open_idx)]
        if sh._DYNAMIC.search(body):
            continue
        tm = _TIER.search(body)
        out[m.group(1)] = tm.group(1) if tm else None
    return out


def load_country_tiers(country_definitions_dir: Path) -> dict[str, str | None]:
    out: dict[str, str | None] = {}
    for path in sorted(Path(country_definitions_dir).glob("*.txt")):
        out.update(parse_country_tiers(path.read_text(encoding="utf-8-sig")))
    return out


def load_effect_names(scripted_effects_dir: Path) -> set[str]:
    """Top-level scripted-effect names defined in ``common/scripted_effects/*.txt``."""
    names: set[str] = set()
    for path in sorted(Path(scripted_effects_dir).glob("*.txt")):
        names |= set(_EFFECT_DEF.findall(sh._strip_comments(path.read_text(encoding="utf-8-sig"))))
    return names


def owner_tags(ownership_doc: dict) -> set[str]:
    """Every tag that owns a state or a slice of one at the start date. The
    ``unowned`` / ``placeholder`` tokens map to ``UNO`` (``state_history.TOKEN_OWNER``),
    so it is an owner whenever any state or slice carries one."""
    states = ownership_doc.get("states")
    if not isinstance(states, dict):
        raise OwnershipError("state_ownership.json has no 'states' object")
    tokens: set[str] = set()
    for key, rec in states.items():
        if rec.get("scope") == "placeholder":
            tokens.add(PLACEHOLDER)
        elif "owner" in rec:
            tokens.add(rec["owner"])
        elif "owners" in rec:
            tokens |= {sl["owner"] for sl in rec["owners"]}
        else:
            raise OwnershipError(f"{key}: record has neither 'owner' nor 'owners'")
    return {sh.TOKEN_OWNER.get(t, t) for t in tokens}


# ---------------------------------------------------------------------------
# Plan / render
# ---------------------------------------------------------------------------

def plan(ownership_doc: dict, tiers: dict[str, str | None]) -> Plan:
    """What to emit. Raises :class:`OwnershipError` for a defined owner whose tier
    has no starting-technology mapping."""
    blocks: list[tuple[str, list[str]]] = []
    held: list[str] = []
    for tag in sorted(owner_tags(ownership_doc)):
        if tag not in tiers:
            held.append(tag)
            continue
        tier = tiers[tag]
        if tier not in TECH_TIER:
            raise OwnershipError(f"c:{tag}: country definition tier {tier!r} has no starting-technology "
                                 f"mapping (known: {', '.join(sorted(TECH_TIER))})")
        blocks.append((tag, [TECH_TIER[tier], POLITICS_EFFECT]))
    return Plan(blocks=blocks, held_back=held)


def render(blocks: list[tuple[str, list[str]]]) -> str:
    """The history file (no BOM, LF). Header comment only when ``blocks`` is empty."""
    if not blocks:
        return HEADER
    lines = [HEADER.rstrip("\n"), "COUNTRIES = {"]
    for tag, effects in blocks:
        lines.append(f"\tc:{tag} ?= {{")
        lines += [f"\t\t{e} = yes" for e in effects]
        lines.append("\t}")
    lines.append("}")
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------------------
# Validate the emitted file
# ---------------------------------------------------------------------------

def parse_history_text(text: str) -> list[tuple[str, list[str]]]:
    """``[(tag, [effect, ...])]`` in file order (duplicates kept). Comments ignored."""
    text = sh._strip_comments(text.lstrip("﻿"))
    out: list[tuple[str, list[str]]] = []
    idx = 0
    while True:
        m = _BLOCK.search(text, idx)
        if not m:
            break
        open_idx = text.index("{", m.end() - 1)
        close_idx = sh._match_brace(text, open_idx)
        out.append((m.group(1), _EFFECT_USE.findall(text[open_idx + 1:close_idx])))
        idx = close_idx + 1
    return out


def check(text: str | None, ownership_doc: dict, tiers: dict[str, str | None],
          effect_names: set[str]) -> tuple[list[str], list[str]]:
    """Validate the emitted file. Returns ``(errors, held_back)``; ``held_back`` lists
    JSON owners with no definition (the caller decides whether that is an error)."""
    try:
        p = plan(ownership_doc, tiers)
    except OwnershipError as exc:
        return [str(exc)], []
    if text is None:
        return ["history/countries/00_start_setup.txt is missing -- run generate_country_history.py"], p.held_back
    errors: list[str] = []
    try:
        parsed = parse_history_text(text)
    except OwnershipError as exc:
        return [f"history/countries/00_start_setup.txt: {exc}"], p.held_back
    seen: dict[str, int] = {}
    for tag, effects in parsed:
        seen[tag] = seen.get(tag, 0) + 1
        if tag not in tiers:
            errors.append(f"c:{tag}: no (non-dynamic) common/country_definitions entry")
        for e in effects:
            if e not in effect_names:
                errors.append(f"c:{tag}: {e} is not a scripted effect in common/scripted_effects")
    for tag, n in sorted(seen.items()):
        if n > 1:
            errors.append(f"c:{tag}: appears {n} times in the country history")
    expected = {tag for tag, _ in p.blocks}
    for tag in sorted(expected - set(seen)):
        errors.append(f"c:{tag}: owns a state but has no country history block -- regenerate")
    for tag in sorted(set(seen) - expected - {t for t in seen if t not in tiers}):
        errors.append(f"c:{tag}: has a country history block but owns no state -- regenerate")
    if not errors and sh.normalize_text(text) != render(p.blocks):
        errors.append("country history differs from what the generator emits (tier or effect changed) -- regenerate")
    return errors, p.held_back
