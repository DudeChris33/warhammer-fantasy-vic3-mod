"""Starting country setup as game script: one file per tag in ``common/history/countries/``.

Every tag that owns a state at the start date (``mapgen/derived/state_ownership.json``)
needs a starting setup or its laws and technology are empty. This module writes
the smallest setup vanilla itself uses for a minimal country, in vanilla's layout of
one file per country (e.g. ``game/common/history/countries/dah - dahomey.txt``;
named ``tag - country name.txt`` from the localized name; the engine reads every file name)::

    COUNTRIES = {
    	c:TAG ?= {
    		effect_starting_technology_empire_tech = yes
    		add_technology_researched = mechanical_tools
    		effect_starting_politics_traditional = yes
    	}
    }

The technology effect is one of this mod's per-culture-group presets in
``common/scripted_effects/00_starting_inventions.txt``; the politics effect is
the vanilla one restored in ``00_political_setup.txt``.

Rules
-----
* One file per owner tag (``file_name``), one block in it: every ``owner`` / ``owners[].owner`` tag, plus ``UNO``
  (Unclaimed Lands, #6391) whenever a state or slice is ``unowned`` or an
  out-of-scope ``placeholder`` -- the same token mapping the state history uses
  (``state_history.TOKEN_OWNER``). A tag with no non-dynamic
  ``common/country_definitions`` entry is **held back** (reported, no block),
  like the state history.
* Starting technology comes from the tag's **first listed culture** in its
  ``common/country_definitions`` entry (``CULTURE_TECH``), unless ``TAG_TECH``
  names the tag (UNO is unclaimed land with no technology). A culture, or a tag without one, that
  neither table covers is an error, never a default. A preset of ``None`` emits
  no technology effect. After the preset, the tag's extras from
  ``mapgen/config/starting_tech_extras.json`` (``add_technology_researched``, one per
  tech, file order; a tech id missing from ``common/technology`` is an error). Every tag gets
  ``effect_starting_politics_traditional``. This is placeholder-grade: it makes
  each country valid, not historically differentiated.
* Ordering is stable (tags sorted), so an ownership repaint does not churn
  unrelated blocks.

Pure and deterministic: no clock, no filesystem beyond the paths handed in.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from pathlib import Path

from . import state_history as sh
from .state_ownership import PLACEHOLDER, OwnershipError

HEADER = ("# GENERATED by mapgen/generate_country_history.py from mapgen/derived/state_ownership.json"
          " and the cultures in common/country_definitions - never hand-edit; repaint"
          " mapgen/config/state_ownership.png, re-read it (read_state_ownership.py) and regenerate.\n")

#: Culture id -> starting-technology preset (``common/scripted_effects/00_starting_inventions.txt``),
