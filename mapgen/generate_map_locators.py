#!/usr/bin/env python3
"""Emit ``gfx/map/map_object_data/generated_map_object_locators_{city,farm,mine,port,wood}.txt``.

Board #6612. A map-object locator's ``id`` is the **state id** (checked against
vanilla: 674 of 675 vanilla city locators sit inside the state whose id they
carry), and its position is where that state's hub building / resource label is
drawn. The engine cannot produce usable ones for this map: with no mod file it
falls back to *vanilla's* table by id (every state id vanilla also has gets
vanilla's Earth position), and with an empty file its own placement lands outside
the state about a third of the time and is not tied to the hub province. The map
editor's Pack + Save only rewrites that same engine output.

So the positions are computed here, one instance per state that has the hub, at
the hub province named by the state file's ``city``/``farm``/``mine``/``wood``/
``port`` key:

* the named hub's anchor from ``mapgen/derived/hub_anchors_index.json`` when it
  lies inside that province (the label sits on the lore settlement itself);
* otherwise the province's pole of inaccessibility (the interior point farthest
  from any border), which is inside the province by construction — this covers
  placeholder / out-of-scope states, which have no hub row.

Frame: provinces.png pixel ``(x, y)`` maps to locator ``position={ x 0 z }`` with
``z = 3616 - y`` (the canvas is 8192x3616, the same frame as vanilla).

Inputs are all committed or generated: ``map_data/state_regions/*.txt``,
``map_data/provinces.png`` and ``hub_anchors_index.json``. The output is a pure
function of them, ascending by state id, byte-identical across runs, and static
data the engine loads identically on every client.

State ids renumber whenever ``generate_land_regions.py`` regenerates, so re-run
this after any such run (the old files are wrong by id, not merely stale).

Usage::

    python mapgen/generate_map_locators.py            # write the five files
    python mapgen/generate_map_locators.py --check    # fail if they are not current
    python mapgen/generate_map_locators.py --verify   # also: every instance lies in its own state
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import numpy as np
from PIL import Image
from scipy import ndimage

TOOLS_DIR = Path(__file__).resolve().parent
MOD_ROOT = TOOLS_DIR.parent
STATE_DIR = MOD_ROOT / "map_data" / "state_regions"
PROVINCES_PNG = MOD_ROOT / "map_data" / "provinces.png"
HUB_INDEX = TOOLS_DIR / "derived" / "hub_anchors_index.json"
OUT_DIR = MOD_ROOT / "gfx" / "map" / "map_object_data"

Image.MAX_IMAGE_PIXELS = None

#: Locator types and the engine's ``clamp_to_water_level`` for each (ports sit on the coast).
TYPES = {"city": "no", "farm": "no", "mine": "no", "port": "yes", "wood": "no"}

ROTATION = "-0.000000 0.000000 -0.000000 1.000000"

HEADER_COMMENT = (
    "# Generated by mapgen/generate_map_locators.py (board #6612) - do not hand-edit.\n"
    "# id = state id; one instance per state with the hub, at the hub province.\n"
)


def parse_states() -> dict[int, dict[str, str]]:
    """``{state id: {hub type: province hex}}`` from the generated state-region files."""
    states: dict[int, dict[str, str]] = {}
    for f in sorted(STATE_DIR.glob("*.txt")):
        text = f.read_text(encoding="utf-8-sig")
        for m in re.finditer(r"(STATE_\w+)\s*=\s*\{(.*?)\n\}", text, re.S):
            body = m.group(2)
            sid = int(re.search(r"\bid\s*=\s*(\d+)", body).group(1))
            hubs: dict[str, str] = {}
            for k in TYPES:
                hm = re.search(rf'\n\s*{k}\s*=\s*"?(x[0-9A-Fa-f]{{6}})"?', body)
                if hm:
                    hubs[k] = "x" + hm.group(1)[1:].upper()
            if sid in states:
                raise SystemExit(f"duplicate state id {sid}")
            states[sid] = hubs
    return states


def load_province_labels() -> tuple[np.ndarray, dict[str, int]]:
    """(label image, ``{hex: label}``); label 0 is unused so ``find_objects`` is 1-based."""
    rgb = np.asarray(Image.open(PROVINCES_PNG).convert("RGB"))
    key = (rgb[:, :, 0].astype(np.uint32) << 16) | (rgb[:, :, 1].astype(np.uint32) << 8) | rgb[:, :, 2]
    uniq, inv = np.unique(key.ravel(), return_inverse=True)
    labels = (inv.reshape(key.shape) + 1).astype(np.int32)
    hex_to_label = {"x%06X" % int(c): i + 1 for i, c in enumerate(uniq)}
    return labels, hex_to_label


def hub_anchors() -> dict[tuple[str, str], tuple[int, int]]:
    """``{(hub type, province hex): anchor pixel}`` from the hub worksheet index."""
    data = json.loads(HUB_INDEX.read_text(encoding="utf-8"))
    out: dict[tuple[str, str], tuple[int, int]] = {}
    for h in data["hubs"]:
        out.setdefault((h["hub"], h["province_hex"].upper().replace("X", "x", 1)), tuple(h["resolved"]))
    return out


def pole(labels: np.ndarray, slices, label: int) -> tuple[int, int]:
    """Interior point of the province farthest from its border (inside by construction)."""
    sl_y, sl_x = slices
    mask = labels[sl_y, sl_x] == label
    padded = np.pad(mask, 1)
    dist = ndimage.distance_transform_edt(padded)[1:-1, 1:-1]
    iy, ix = np.unravel_index(int(np.argmax(dist)), dist.shape)
    return sl_x.start + int(ix), sl_y.start + int(iy)


def compute() -> dict[str, list[tuple[int, float, float]]]:
    """``{type: [(state id, x, z)]}`` ascending by state id."""
    states = parse_states()
    labels, hex_to_label = load_province_labels()
    height = labels.shape[0]
    anchors = hub_anchors()
    objects = ndimage.find_objects(labels)
    out: dict[str, list[tuple[int, float, float]]] = {k: [] for k in TYPES}
    for sid in sorted(states):
        for k, hexcol in states[sid].items():
            label = hex_to_label.get(hexcol)
            if label is None:
                raise SystemExit(f"state {sid}: {k} province {hexcol} is not in provinces.png")
            ax = anchors.get((k, hexcol))
            if ax is not None and labels[ax[1], ax[0]] == label:
                px, py = ax
            else:
                px, py = pole(labels, objects[label - 1], label)
            out[k].append((sid, px + 0.5, height - (py + 0.5)))
    return out


def render(k: str, rows: list[tuple[int, float, float]]) -> str:
    lines = [
        HEADER_COMMENT.rstrip("\n"),
        "game_object_locator={",
        f'\tname="{k}"',
        f"\tclamp_to_water_level={TYPES[k]}",
        "\trender_under_water=no",
        "\tgenerated_content=no",
        '\tlayer="locators"',
        "\tinstances={",
    ]
    for sid, x, z in rows:
        lines += [
            "\t\t{",
            f"\t\t\tid={sid}",
            f"\t\t\tposition={{ {x:.6f} 0.000000 {z:.6f} }}",
            f"\t\t\trotation={{ {ROTATION} }}",
            "\t\t\tscale={ 1.000000 1.000000 1.000000 }",
            "\t\t}",
        ]
    lines += ["\t}", "}"]
    return "\n".join(lines) + "\n"


def verify(computed: dict[str, list[tuple[int, float, float]]]) -> int:
    """Every instance's pixel must be inside its own state; returns the failure count."""
    labels, hex_to_label = load_province_labels()
    height = labels.shape[0]
    # Map each province label to its state through the state's province list.
    prov_to_state: dict[int, int] = {}
    for f in sorted(STATE_DIR.glob("*.txt")):
        for m in re.finditer(r"(STATE_\w+)\s*=\s*\{(.*?)\n\}", f.read_text(encoding="utf-8-sig"), re.S):
            sid = int(re.search(r"\bid\s*=\s*(\d+)", m.group(2)).group(1))
            for p in re.search(r"provinces\s*=\s*\{([^}]*)\}", m.group(2)).group(1).replace('"', "").split():
                prov_to_state[hex_to_label[("x" + p[1:].upper())]] = sid
    bad = 0
    for k, rows in computed.items():
        for sid, x, z in rows:
            lab = int(labels[int(round(height - z - 0.5)), int(round(x - 0.5))])
            if prov_to_state.get(lab) != sid:
                bad += 1
                print(f"  outside own state: {k} state {sid} at ({x}, {z})")
    return bad


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if the committed files are not current")
    ap.add_argument("--verify", action="store_true", help="also assert every instance lies in its own state")
    args = ap.parse_args(argv)

    computed = compute()
    texts = {k: render(k, computed[k]) for k in TYPES}
    rc = 0
    for k, text in texts.items():
        path = OUT_DIR / f"generated_map_object_locators_{k}.txt"
        if args.check:
            cur = path.read_bytes().decode("utf-8") if path.is_file() else None
            if cur != text:
                print(f"STALE {path.relative_to(MOD_ROOT)}")
                rc = 1
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(text.encode("utf-8"))  # binary write keeps LF, no BOM
            print(f"wrote {path.relative_to(MOD_ROOT)}  ({len(computed[k])} instances)")
    if args.verify:
        bad = verify(computed)
        print(f"verify: {bad} instance(s) outside their own state")
        rc = rc or (1 if bad else 0)
    return rc


if __name__ == "__main__":
    sys.exit(main())
