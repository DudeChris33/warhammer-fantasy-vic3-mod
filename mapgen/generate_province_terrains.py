#!/usr/bin/env python3
"""Emit ``map_data/province_terrains.txt`` — one terrain line per province.

Board #2968 (bootable-map map-config). A fully-blanked ``map_data`` (both
``map_data`` and ``map_data/state_regions`` are in ``.metadata/metadata.json``'s
``replace_paths``, so the engine loads *none* of vanilla's map files) needs a
``province_terrains.txt`` of its own: vanilla ships one ``x<HEX>="terrain"`` line
per province, and this is the one game-required map-config file no sibling
emitter (#2929 seas / #2930/#2931 land) writes.

This is the direct analogue of #3542's header-only ``adjacencies.csv``: a
uniform, boot-valid **placeholder baseline**, not real terrain. Real
(heightmap-/source-derived) terrain is a future sourcing-driven item and is
deliberately out of scope here — there is no painted terrain source in
``sources/`` yet, and terrain *quality* is a user-owned visual step, not offline
tuning.

Assignment (design decision, board #2968):

* **land province -> ``"plains"``** — vanilla's own natural default and a defined
  id in this mod's ``common/terrain/01_terrain.txt``. Placeholder / out-of-scope
  land still gets ``plains``; terrain is orthogonal to passable/impassable, which
  lives in ``state_regions``.
* **sea province -> ``"ocean"``** — also defined in the mod's terrain file.
* **lake province -> ``"lakes"``** (board #3742) — inland water, defined in the
  mod's terrain file. Only present when the index carries ``kind == "lake"`` cells
  (a lake companion layer was generated); absent, the output is byte-identical to
  the two-class land/ocean baseline.

Colour authority: ``mapgen/derived/provinces_index.json`` -> ``cells``. Each cell
carries ``hex`` (e.g. ``xD35EE9`` — the exact ``province_terrains.txt`` key
format: ``x`` prefix, uppercase, ``R<<16 | G<<8 | B``) and ``kind``
(``land``/``sea``/``lake``). This is the same index that coloured ``provinces.png``
(board #2773), so the terrains and the bitmap agree by construction. Kind is read
from ``cell["kind"]`` (not an id-threshold guess), so this stays correct if the
land/sea id bands ever move.

Deterministic: the output is a pure function of the committed index, sorted by
integer ``id``; two runs are byte-identical. It is a static data file the engine
loads identically on every client — not a runtime MP-sync vector.

Sequencing note (board #2968, confirmed): ``provinces.png`` is under active churn
(the lore-hubs epic #3663/#3664/#3665) and every regen reshuffles every province
colour (#3705), so the committed ``province_terrains.txt`` is the same
colour-keyed fragility class as the already-committed ``99_seas.txt`` / land
``state_regions/*.txt``. Re-run this generator alongside ``generate_sea_regions.py``
and ``generate_land_regions.py`` after any ``generate_provinces.py`` regen.

Run ``generate_provinces.py`` first (it writes the index this reads).

Usage::

    python mapgen/generate_province_terrains.py
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

TOOLS_DIR = Path(__file__).resolve().parent
MOD_ROOT = TOOLS_DIR.parent
DERIVED_DIR = TOOLS_DIR / "derived"
PROVINCES_INDEX_PATH = DERIVED_DIR / "provinces_index.json"
TERRAINS_PATH = MOD_ROOT / "map_data" / "province_terrains.txt"

#: Terrain id per province kind. All three ids are defined in the mod's own
#: ``common/terrain/01_terrain.txt`` (``common/terrain`` is in ``replace_paths``,
#: so only mod-defined ids are valid). ``lake -> "lakes"`` is board #3742's inland
#: water class; absent lakes leave this mapping unused (byte-identical output).
TERRAIN_BY_KIND = {"land": "plains", "sea": "ocean", "lake": "lakes"}

#: Header comment. Deliberately NOT vanilla's "do not modify unless you know what
#: you are doing" wording — it says what actually generates this file here.
HEADER = (
    "# Generated by mapgen/generate_province_terrains.py (board #2968) - do not hand-edit.\n"
    "# One line per province in mapgen/derived/provinces_index.json, sorted by id.\n"
    "# Placeholder baseline: every land province is \"plains\", every sea province\n"
    "# is \"ocean\". Real terrain is a future sourcing-driven pass - regenerate\n"
    "# this file (with the sea/land state emitters) after any generate_provinces.py run.\n"
)


def render_terrains(cells: list[dict]) -> str:
    """The full file text for a list of provinces-index ``cells``.

    One ``x<HEX>="terrain"`` line per cell, sorted by integer ``id`` (stable and
    reproducible). Pure function of the cells — no I/O — so the fixture self-check
    can exercise it directly. Errors loudly on an empty cell list or an
    unrecognised kind rather than writing a truncated / silently-wrong file.
    """
    if not cells:
        raise SystemExit("provinces_index.json has no cells — refusing to write an empty terrains file")
    lines = [HEADER.rstrip("\n")]
    for c in sorted(cells, key=lambda c: int(c["id"])):
        kind = c["kind"]
        terrain = TERRAIN_BY_KIND.get(kind)
        if terrain is None:
            raise SystemExit(f"province id {c.get('id')} has unknown kind {kind!r}")
        lines.append(f'{c["hex"]}="{terrain}"')
    # Vanilla ends the file with a trailing newline (ASCII/LF, no BOM); mirror it.
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    ).parse_args(argv)
    if not PROVINCES_INDEX_PATH.is_file():
        raise SystemExit(f"{PROVINCES_INDEX_PATH} not found — run mapgen/generate_provinces.py first")

    index = json.loads(PROVINCES_INDEX_PATH.read_text(encoding="utf-8"))
    cells = index.get("cells") or []
    text = render_terrains(cells)

    TERRAINS_PATH.parent.mkdir(parents=True, exist_ok=True)
    TERRAINS_PATH.write_bytes(text.encode("utf-8"))  # binary write keeps LF, no BOM

    n_land = sum(1 for c in cells if c["kind"] == "land")
    n_sea = sum(1 for c in cells if c["kind"] == "sea")
    n_lake = sum(1 for c in cells if c["kind"] == "lake")
    print(f"wrote {TERRAINS_PATH.relative_to(MOD_ROOT)}  "
          f"({len(cells)} provinces: {n_land} plains, {n_sea} ocean, {n_lake} lakes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
