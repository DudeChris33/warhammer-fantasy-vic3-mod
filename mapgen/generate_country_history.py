#!/usr/bin/env python3
"""Write starting country setup into ``common/history/countries/<tag> - <name>.txt``, one file per tag.

Reads ``mapgen/derived/state_ownership.json`` (``read_state_ownership.py``) for the
tags that own a state at the start date, and ``common/country_definitions/*.txt``
for each tag's ``cultures``, and writes one file per owner (vanilla's layout), each holding one ``c:TAG ?= { ... }`` block:
the starting-technology preset of its first culture (``worldgen/country_history.CULTURE_TECH``) plus
the tag's extras from ``mapgen/config/starting_tech_extras.json``,
``effect_starting_politics_traditional`` and the tag's starting laws (today the slavery law, resolved from
``mapgen/config/country_history/*.json`` by ``worldgen/country_config``, the same resolver the slave-pop
gate reads), plus ``law_isolationism`` for a tag whose technologies lack the trade-law gate. Rules are in
``worldgen/country_history.py``.

Runs after ``read_state_ownership.py`` (the same input as
``generate_state_history.py``): a repaint changes the owner set, so re-run both.
Output is UTF-8 with a BOM and LF endings, like the sibling generated files. Stale
generated files (an old ``00_start_setup.txt``, a tag that no longer owns a state)
are removed; a file without the GENERATED header is never touched. Generated: never
hand-edit.

Usage::

    python mapgen/generate_country_history.py           # write the file
    python mapgen/generate_country_history.py --check   # exit 1 if it is stale (BOM/CRLF-insensitive)
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from worldgen import country_config  # noqa: E402
from worldgen import country_history as ch  # noqa: E402
from worldgen import state_history as sh  # noqa: E402
from worldgen.state_ownership import OwnershipError  # noqa: E402

MOD_ROOT = Path(__file__).resolve().parent.parent
OWNERSHIP_PATH = MOD_ROOT / "mapgen" / "derived" / "state_ownership.json"
COUNTRY_DEFS_DIR = MOD_ROOT / "common" / "country_definitions"
LOC_DIR = MOD_ROOT / "localization"
LAWS_DIR = MOD_ROOT / "common" / "laws"
SCRIPTED_EFFECTS_DIR = MOD_ROOT / "common" / "scripted_effects"
COUNTRY_HISTORY_CONFIG_DIR = MOD_ROOT / "mapgen" / "config" / "country_history"
TECH_EXTRAS_PATH = MOD_ROOT / "mapgen" / "config" / "starting_tech_extras.json"
TECHNOLOGIES_DIR = MOD_ROOT / "common" / "technology" / "technologies"
OUT_DIR = MOD_ROOT / "common" / "history" / "countries"
BOM = b"\xef\xbb\xbf"
GENERATED_PREFIX = "# GENERATED by mapgen/generate_country_history.py"


def summary(p: ch.Plan) -> str:
    lines = [f"{len(p.blocks)} country blocks, {len(p.held_back)} held back"]
    laws = [x for _, effects in p.blocks for x in effects if x.startswith(ch.ACTIVATE_LAW)]
    if laws:
        counts = {law: laws.count(law) for law in sorted(set(laws))}
        lines.append("  starting laws: " + ", ".join(f"{k[len(ch.ACTIVATE_LAW):]} x{v}" for k, v in counts.items()))
    if p.held_back:
        lines.append(f"  held back (owner tag undefined): {', '.join(p.held_back)}")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--ownership", type=Path, default=OWNERSHIP_PATH)
    ap.add_argument("--country-definitions", type=Path, default=COUNTRY_DEFS_DIR)
    ap.add_argument("--localization", type=Path, default=LOC_DIR)
    ap.add_argument("--tech-extras", type=Path, default=TECH_EXTRAS_PATH)
    ap.add_argument("--laws", type=Path, default=LAWS_DIR, help="common/laws (the trade-law tech gate)")
    ap.add_argument("--scripted-effects", type=Path, default=SCRIPTED_EFFECTS_DIR,
                    help="common/scripted_effects (the starting-technology presets)")
    ap.add_argument("--country-history", type=Path, default=COUNTRY_HISTORY_CONFIG_DIR,
                    help="mapgen/config/country_history (the starting laws)")
    ap.add_argument("--technologies", type=Path, default=TECHNOLOGIES_DIR)
    ap.add_argument("--out", type=Path, default=OUT_DIR, help="the common/history/countries folder")
    ap.add_argument("--check", action="store_true", help="assert the file on disk is current; write nothing")
    args = ap.parse_args(argv)
    try:
        doc = json.loads(args.ownership.read_text(encoding="utf-8"))
        extras = ch.load_tech_extras(args.tech_extras)
        unknown = sorted((t, x) for t, v in extras.items() for x in v if x not in ch.load_tech_ids(args.technologies))
        if unknown:
            raise OwnershipError(f"{args.tech_extras.name}: technology id(s) not in common/technology: "
                                 + ", ".join(f"{t}:{x}" for t, x in unknown))
        resolved = country_config.load_resolved(args.country_history)
        laws = None if resolved is None else country_config.starting_laws(resolved)
        p = ch.plan(doc, ch.load_country_cultures(args.country_definitions), extras, laws,
                    ch.load_preset_techs(args.scripted_effects), ch.load_trade_gate(args.laws))
    except OwnershipError as exc:
        print(f"generate_country_history: ERROR: {exc}", file=sys.stderr)
        return 1
    want = ch.render(p.blocks, ch.load_country_names(args.localization))
    have = ch.load_history_dir(args.out)
    stale = {n for n, t in have.items() if n not in want and t.lstrip("﻿").startswith(GENERATED_PREFIX)}
    if args.check:
        current = {n: sh.normalize_text(t) for n, t in have.items() if n in want or n in stale}
        if current != want:
            print(f"generate_country_history: stale: {args.out} -- re-run without --check", file=sys.stderr)
            return 1
        print(f"generate_country_history: output is current. {summary(p)}")
        return 0
    args.out.mkdir(parents=True, exist_ok=True)
    for name in sorted(stale):
        (args.out / name).unlink()
    for name, text in want.items():
        (args.out / name).write_bytes(BOM + text.encode("utf-8"))
    print(f"generate_country_history: wrote {len(want)} files to {args.out}, removed {len(stale)}: {summary(p)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
